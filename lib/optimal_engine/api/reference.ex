defmodule OptimalEngine.API.Reference do
  @moduledoc """
  Renders the public API reference from the routers themselves.

  A hand-maintained endpoint list drifts the first time somebody adds a route.
  This module reads the route macros out of `OptimalEngine.API.Router` and the
  routers it forwards to, so the published reference is a function of the code.
  `mix optimal.api.reference --check` fails when `docs/reference/api.md` is
  stale, and conformance runs the same check.

  Only the route table is generated. Scope rules stay in
  `OptimalEngine.API.PermissionPlug`, which is the code that enforces them.
  """

  @main_router "lib/optimal_engine/api/router.ex"
  @output "docs/reference/api.md"

  @route_re ~r/^\s*(get|post|put|patch|delete)\s*\(?\s*"(\/[^"]*)"/
  @mount_re ~r/^\s*forward\("(\/api\/[^"]+)",\s*to:\s*([A-Za-z0-9_.]+)\)/

  @method_order %{"GET" => 0, "POST" => 1, "PUT" => 2, "PATCH" => 3, "DELETE" => 4}

  @type route :: %{method: String.t(), path: String.t(), router: String.t()}

  @doc "The reference file path for a repository root."
  @spec output_path(Path.t()) :: Path.t()
  def output_path(root), do: Path.join(root, @output)

  @doc """
  Every public route this build serves, sorted by path then method.

  Routes forwarded to a sub-router are prefixed with the mount path, because
  that is the path a client calls.
  """
  @spec routes(Path.t()) :: [route()]
  def routes(root) do
    main = File.read!(Path.join(root, @main_router))

    direct =
      main
      |> extract("Router")
      |> Enum.filter(&String.starts_with?(&1.path, "/api/"))

    forwarded =
      for {prefix, module} <- mounts(main),
          {:ok, source} <- [read_module(root, module)],
          route <- extract(source, short_name(module)) do
        %{route | path: normalize(prefix <> route.path)}
      end

    (direct ++ forwarded)
    |> Enum.uniq_by(&{&1.method, &1.path})
    |> Enum.sort_by(&{&1.path, Map.get(@method_order, &1.method, 9), &1.method})
  end

  @doc "The full Markdown document for a repository root."
  @spec render(Path.t()) :: String.t()
  def render(root) do
    routes = routes(root)

    groups =
      routes
      |> Enum.group_by(& &1.path)
      |> Enum.sort_by(fn {path, _} -> path end)

    rows =
      Enum.map(groups, fn {_path, [route | _] = routes_for_path} ->
        methods =
          routes_for_path |> Enum.map(& &1.method) |> Enum.sort_by(&Map.get(@method_order, &1, 9))

        "| #{Enum.join(methods, ", ")} | `#{route.path}` | #{route.router} |"
      end)

    """
    # API Reference

    Generated from the routers by `mix optimal.api.reference`.
    Do not edit this file by hand: change a route, then run the task, and CI fails when the two disagree.

    Every route below is served under `/api`.
    A request carries `Authorization: Bearer oe_<id>_<secret>` unless the Engine runs with `OPTIMAL_AUTH_REQUIRED=false`.
    Authentication, workspace scope, and operation grants are enforced by `OptimalEngine.API.PermissionPlug`; `read` and `write` cover ordinary operations, while administration, app-data schema changes, claim review, and authority operations require their own grant.

    Routes: #{length(routes)}

    | Method | Path | Router |
    | --- | --- | --- |
    #{Enum.join(rows, "\n")}
    """
  end

  @doc """
  Compares the rendered reference with the file on disk.

  Returns `:ok` or `{:drift, %{documented: n, actual: n, missing: [...], extra: [...]}}`
  where `missing` routes exist in the code but not the document and `extra`
  routes are documented but no longer served.
  """
  @spec check(Path.t()) :: :ok | {:drift, map()}
  def check(root) do
    path = output_path(root)
    actual = routes(root)

    case File.read(path) do
      {:ok, content} ->
        if content == render(root) do
          :ok
        else
          documented = documented_routes(content)

          {:drift,
           %{
             documented: length(documented),
             actual: length(actual),
             missing: actual -- documented,
             extra: documented -- actual
           }}
        end

      {:error, reason} ->
        {:drift,
         %{documented: 0, actual: length(actual), missing: actual, extra: [], reason: reason}}
    end
  end

  # ---------------------------------------------------------------------------
  # Parsing
  # ---------------------------------------------------------------------------

  defp extract(source, router) do
    source
    |> String.split("\n")
    |> Enum.flat_map(fn line ->
      case Regex.run(@route_re, line) do
        [_, method, path] ->
          [%{method: String.upcase(method), path: normalize(path), router: router}]

        _ ->
          []
      end
    end)
  end

  defp mounts(source) do
    source
    |> String.split("\n")
    |> Enum.flat_map(fn line ->
      case Regex.run(@mount_re, line) do
        [_, prefix, module] -> [{prefix, module}]
        _ -> []
      end
    end)
  end

  defp read_module(root, module) do
    relative = "lib/optimal_engine/api/" <> Macro.underscore(short_name(module)) <> ".ex"
    path = Path.join(root, relative)
    if File.exists?(path), do: {:ok, File.read!(path)}, else: :error
  end

  defp short_name(module), do: module |> String.split(".") |> List.last()

  defp normalize(path) do
    path
    |> String.replace(~r{/+}, "/")
    |> String.trim_trailing("/")
    |> case do
      "" -> "/"
      normalized -> normalized
    end
  end

  defp documented_routes(content) do
    content
    |> String.split("\n")
    |> Enum.flat_map(fn line ->
      case Regex.run(~r/^\|\s*([A-Z, ]+)\s*\|\s*`([^`]+)`\s*\|\s*([^|]+?)\s*\|$/, line) do
        [_, methods, path, router] ->
          for method <- String.split(methods, ","),
              do: %{method: String.trim(method), path: path, router: String.trim(router)}

        _ ->
          []
      end
    end)
  end
end
