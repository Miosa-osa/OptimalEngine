  defp log_schema(txn, scope, c, detail) do
    log_change(
      txn,
      scope,
      c,
      "schema",
      nil,
      nil,
      nil,
      Map.put(detail, "schema_version", c.schema_version)
    )
  end

  @doc false
  @spec log_change(
          term(),
          Scope.t(),
          t(),
          String.t(),
          String.t() | nil,
          integer() | nil,
          String.t() | nil,
          term(),
          String.t() | nil
        ) ::
          :ok | {:error, term()}
  def log_change(txn, scope, c, op, record_id, version, owner, data, txn_id \\ nil) do
    sql = """
    INSERT INTO data_changes
      (tenant_id, workspace_id, collection_id, collection, record_id, op, version, owner, actor, data, txn_id, at)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """

    params = [
      scope.tenant_id,
      scope.workspace_id,
      c.id,
      c.name,
      record_id,
      op,
      version,
      owner,
      scope.actor,
      data && Jason.encode!(data),
      txn_id,
      Schema.now()
    ]

    case SQL.exec(txn, sql, params) do
      {:ok, 1} -> :ok
      error -> error
    end
  end

  defp from_row([
         id,
         name,
         table,
         schema,
         version,
         tenant_id,
         workspace_id,
         created_by,
         created_at,
         updated_at
       ]) do
    %{
      id: id,
      name: name,
      table: table,
      schema: Jason.decode!(schema),
      schema_version: version,
      tenant_id: tenant_id,
      workspace_id: workspace_id,
      created_by: created_by,
      created_at: created_at,
      updated_at: updated_at
    }
  end
