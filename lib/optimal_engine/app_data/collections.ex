defmodule OptimalEngine.AppData.Collections do
  @moduledoc """
  Collection registry and DDL for app data.

  Each collection is one row in `data_collections` plus one STRICT SQLite
  table named `appdata_<id>`, where the id is generated by the Engine. The
  table holds the system columns (`_rowid`, `id`, `_version`, timestamps,
  actors) and one `f_<field>` column per declared field. Declared indexes
  are SQLite indexes on that table; full-text search fields are an FTS5
  external-content table kept in sync by triggers; reference fields are
  foreign keys to the referenced collection's `id`.

  Schema changes run inside one Store transaction, so a failed alteration
  leaves the collection exactly as it was. Destructive changes (dropping a
  field or the collection) must be confirmed explicitly.
  """

  alias OptimalEngine.AppData.{Schema, Scope, SQL}
  alias OptimalEngine.Store

  @max_collections 1_000

  @type t :: %{
          id: String.t(),
          name: String.t(),
          table: String.t(),
          schema: map(),
          schema_version: pos_integer(),
          tenant_id: String.t(),
          workspace_id: String.t(),
          created_by: String.t() | nil,
          created_at: String.t(),
          updated_at: String.t()
        }

  @columns "id, name, table_name, schema, schema_version, tenant_id, workspace_id, created_by, created_at, updated_at"

  # ---------------------------------------------------------------------------
  # Reads
  # ---------------------------------------------------------------------------

  @doc "Loads collection `name` in the scope's workspace."
  @spec load(:store | term(), Scope.t(), String.t()) :: {:ok, t()} | {:error, term()}
  def load(conn, %Scope{} = scope, name) when is_binary(name) do
    sql =
      "SELECT #{@columns} FROM data_collections WHERE tenant_id = ? AND workspace_id = ? AND name = ?"

    case SQL.query(conn, sql, [scope.tenant_id, scope.workspace_id, name]) do
      {:ok, [row]} -> {:ok, from_row(row)}
      {:ok, []} -> {:error, {:not_found, "collection_not_found"}}
      {:error, _} = error -> error
    end
  end

  def load(_conn, _scope, _name), do: {:error, {:not_found, "collection_not_found"}}

  @doc "All collections in the scope's workspace, by name."
  @spec load_all(:store | term(), Scope.t()) :: {:ok, [t()]} | {:error, term()}
  def load_all(conn, %Scope{} = scope) do
    sql =
      "SELECT #{@columns} FROM data_collections WHERE tenant_id = ? AND workspace_id = ? ORDER BY name"

    with {:ok, rows} <- SQL.query(conn, sql, [scope.tenant_id, scope.workspace_id]) do
      {:ok, Enum.map(rows, &from_row/1)}
    end
  end

  @doc "Collections the scope may read."
  @spec list(Scope.t()) :: {:ok, [map()]} | {:error, term()}
  def list(%Scope{} = scope) do
    with {:ok, collections} <- load_all(:store, scope) do
      {:ok, for(c <- collections, Scope.readable?(scope, c.name), do: view(c))}
    end
  end

  @doc "A collection's definition plus its record count."
  @spec describe(Scope.t(), String.t()) :: {:ok, map()} | {:error, term()}
  def describe(%Scope{} = scope, name) do
    with :ok <- Scope.allow(scope, name, "read"),
         {:ok, c} <- load(:store, scope, name),
         {:ok, count} <- SQL.scalar(:store, ~s[SELECT COUNT(*) FROM "#{c.table}"], []) do
      {:ok, c |> view() |> Map.put("record_count", count)}
    end
  end

  @doc "The API view of a collection."
  @spec view(t()) :: map()
  def view(c) do
    %{
      "id" => c.id,
      "name" => c.name,
      "workspace" => c.workspace_id,
      "schema_version" => c.schema_version,
      "fields" => c.schema["fields"],
      "indexes" => c.schema["indexes"],
      "owner_field" => c.schema["owner_field"],
      "search" => c.schema["search"],
      "created_by" => c.created_by,
      "created_at" => c.created_at,
      "updated_at" => c.updated_at
    }
  end

  @doc "Name of the FTS5 table for a collection table."
  @spec fts_table(t()) :: String.t()
  def fts_table(c), do: c.table <> "_fts"

  # ---------------------------------------------------------------------------
  # Create
  # ---------------------------------------------------------------------------

  @doc "Creates a collection from a definition (see `Schema.normalize_definition/1`)."
  @spec create(Scope.t(), map()) :: {:ok, map()} | {:error, term()}
  def create(%Scope{} = scope, definition) do
    with :ok <- Scope.allow_admin(scope),
         {:ok, schema} <- Schema.normalize_definition(definition) do
      Store.transaction(fn txn ->
        with {:ok, c} <- create_in(txn, scope, schema),
             :ok <- log_schema(txn, scope, c, %{"action" => "create"}) do
          {:ok, view(c)}
        end
      end)
    end
  end

  @doc false
  # Creates a collection inside an open transaction. Used by `create/2` and
  # by app schema migrations.
  @spec create_in(term(), Scope.t(), map()) :: {:ok, t()} | {:error, term()}
  def create_in(txn, scope, %{"name" => name} = schema) do
    id = Base.encode16(:crypto.strong_rand_bytes(8), case: :lower)
    table = "appdata_" <> id
    schema = Map.delete(schema, "name")

    with :ok <- ensure_absent(txn, scope, name),
         :ok <- ensure_capacity(txn, scope),
         {:ok, targets} <- reference_targets(txn, scope, name, table, schema),
         :ok <- SQL.exec_all(txn, [create_table_sql(table, schema, targets)]),
         :ok <- create_indexes(txn, table, schema["indexes"]),
         :ok <- create_fts(txn, table, Schema.text_fields(schema)),
         now = Schema.now(),
         {:ok, 1} <-
           SQL.exec(
             txn,
             "INSERT INTO data_collections (id, tenant_id, workspace_id, name, table_name, schema, schema_version, created_by, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, 1, ?, ?, ?)",
             [
               id,
               scope.tenant_id,
               scope.workspace_id,
               name,
               table,
               Jason.encode!(schema),
               scope.actor,
               now,
               now
             ]
           ) do
      {:ok,
       %{
         id: id,
         name: name,
         table: table,
         schema: schema,
         schema_version: 1,
         tenant_id: scope.tenant_id,
         workspace_id: scope.workspace_id,
         created_by: scope.actor,
         created_at: now,
         updated_at: now
       }}
    end
  end

  defp ensure_absent(txn, scope, name) do
    case load(txn, scope, name) do
      {:ok, _c} -> {:error, {:conflict, "collection_exists", %{}}}
      {:error, {:not_found, _}} -> :ok
      {:error, _} = error -> error
    end
  end

  defp ensure_capacity(txn, scope) do
    case SQL.scalar(
           txn,
           "SELECT COUNT(*) FROM data_collections WHERE tenant_id = ? AND workspace_id = ?",
           [scope.tenant_id, scope.workspace_id]
         ) do
      {:ok, count} when count < @max_collections ->
        :ok

      {:ok, _count} ->
        {:error, {:validation, ["a workspace may hold at most #{@max_collections} collections"]}}

      {:error, _} = error ->
        error
    end
  end

  # Map of reference field name to the referenced table. A collection may
  # reference itself.
  defp reference_targets(txn, scope, own_name, own_table, schema) do
    schema["fields"]
    |> Enum.filter(&(&1["type"] == "reference"))
    |> Enum.reduce_while({:ok, %{}}, fn field, {:ok, acc} ->
      target = field["references"]

      cond do
        target == own_name ->
          {:cont, {:ok, Map.put(acc, field["name"], own_table)}}

        true ->
          case load(txn, scope, target) do
            {:ok, c} ->
              {:cont, {:ok, Map.put(acc, field["name"], c.table)}}

            {:error, {:not_found, _}} ->
              {:halt,
               {:error,
                {:validation, ["field #{field["name"]}: referenced collection #{target} not found"]}}}

            error ->
              {:halt, error}
          end
      end
    end)
  end

  defp create_table_sql(table, schema, targets) do
    columns =
      [
        ~s["_rowid" INTEGER PRIMARY KEY],
        ~s["id" TEXT NOT NULL UNIQUE],
        ~s["_version" INTEGER NOT NULL DEFAULT 1],
        ~s["_created_at" TEXT NOT NULL],
        ~s["_updated_at" TEXT NOT NULL],
        ~s["_created_by" TEXT],
        ~s["_updated_by" TEXT]
      ] ++ Enum.map(schema["fields"], &column_sql(&1, targets))

    ~s[CREATE TABLE "#{table}" (#{Enum.join(columns, ", ")}) STRICT]
  end

  defp column_sql(field, targets) do
    base = "#{Schema.column(field["name"])} #{Schema.sql_type(field["type"])}"

    case Map.fetch(targets, field["name"]) do
      {:ok, target_table} -> ~s[#{base} REFERENCES "#{target_table}"("id")]
      :error -> base
    end
  end

  defp create_indexes(txn, table, indexes) do
    SQL.exec_all(txn, Enum.map(indexes, &index_sql(table, &1)))
  end

  defp index_sql(table, index) do
    unique = if index["unique"], do: "UNIQUE ", else: ""
    columns = Enum.map_join(index["fields"], ", ", &Schema.column/1)
    ~s[CREATE #{unique}INDEX "#{table}__#{index["name"]}" ON "#{table}"(#{columns})]
  end

  # Full-text search: an FTS5 table over the collection table's rows (keyed
  # by `_rowid`), kept in sync by insert, delete, and update triggers.
  defp create_fts(_txn, _table, []), do: :ok

  defp create_fts(txn, table, fields) do
    fts = table <> "_fts"
    cols = Enum.map_join(fields, ", ", &Schema.column/1)
    new_vals = Enum.map_join(fields, ", ", &("new." <> Schema.column(&1)))
    old_vals = Enum.map_join(fields, ", ", &("old." <> Schema.column(&1)))

    SQL.exec_all(txn, [
      ~s[CREATE VIRTUAL TABLE "#{fts}" USING fts5(#{cols}, content='#{table}', content_rowid='_rowid', tokenize='unicode61 remove_diacritics 2')],
      ~s[CREATE TRIGGER "#{fts}_ai" AFTER INSERT ON "#{table}" BEGIN INSERT INTO "#{fts}"(rowid, #{cols}) VALUES (new."_rowid", #{new_vals}); END],
      ~s[CREATE TRIGGER "#{fts}_ad" AFTER DELETE ON "#{table}" BEGIN INSERT INTO "#{fts}"("#{fts}", rowid, #{cols}) VALUES ('delete', old."_rowid", #{old_vals}); END],
      ~s[CREATE TRIGGER "#{fts}_au" AFTER UPDATE OF #{cols} ON "#{table}" BEGIN INSERT INTO "#{fts}"("#{fts}", rowid, #{cols}) VALUES ('delete', old."_rowid", #{old_vals}); INSERT INTO "#{fts}"(rowid, #{cols}) VALUES (new."_rowid", #{new_vals}); END],
      ~s[INSERT INTO "#{fts}"("#{fts}") VALUES ('rebuild')]
    ])
  end

  defp drop_fts(txn, table) do
    fts = table <> "_fts"

    SQL.exec_all(txn, [
      ~s[DROP TRIGGER IF EXISTS "#{fts}_ai"],
      ~s[DROP TRIGGER IF EXISTS "#{fts}_ad"],
      ~s[DROP TRIGGER IF EXISTS "#{fts}_au"],
      ~s[DROP TABLE IF EXISTS "#{fts}"]
    ])
  end

  # ---------------------------------------------------------------------------
  # Alter
  # ---------------------------------------------------------------------------

  @doc """
  Applies schema `operations` to a collection in one transaction:

  * `add_field` `{"field": {...}}` - a required field needs a default when
    the collection has rows; the default backfills existing rows.
  * `drop_field` `{"name": f, "confirm": true}` - destructive.
  * `set_default` `{"name": f, "default": v}` (null clears it).
  * `set_required` `{"name": f, "required": bool}` - requires no null rows.
  * `add_index` `{"fields": [...], "unique": bool, "name": n}`.
  * `drop_index` `{"name": n}`.
  * `set_search` `{"text": [...], "semantic": [...]}` - rebuilds the
    full-text index; changing semantic fields clears stored embeddings.
  * `set_owner_field` `{"name": f}` - `null` clears it and needs `confirm`.
  """
  @spec alter(Scope.t(), String.t(), term()) :: {:ok, map()} | {:error, term()}
  def alter(%Scope{} = scope, name, operations) do
    with :ok <- Scope.allow_admin(scope) do
      Store.transaction(fn txn ->
        with {:ok, c} <- load(txn, scope, name),
             {:ok, c} <- alter_in(txn, scope, c, operations) do
          {:ok, view(c)}
        end
      end)
    end
  end

  @doc false
  @spec alter_in(term(), Scope.t(), t(), term()) :: {:ok, t()} | {:error, term()}
  def alter_in(txn, scope, c, operations) when is_list(operations) and operations != [] do
    result =
      operations
      |> Enum.with_index()
      |> Enum.reduce_while({:ok, c}, fn {op, index}, {:ok, acc} ->
        case alter_op(txn, scope, acc, op) do
          {:ok, acc} -> {:cont, {:ok, acc}}
          {:error, reason} -> {:halt, {:error, {:operation_failed, index, reason}}}
        end
      end)

    with {:ok, altered} <- result,
         now = Schema.now(),
         version = c.schema_version + 1,
         {:ok, 1} <-
           SQL.exec(
             txn,
             "UPDATE data_collections SET schema = ?, schema_version = ?, updated_at = ? WHERE id = ?",
             [Jason.encode!(altered.schema), version, now, c.id]
           ),
         altered = %{altered | schema_version: version, updated_at: now},
         :ok <- log_schema(txn, scope, altered, %{"action" => "alter", "operations" => operations}) do
      {:ok, altered}
    end
  end

  def alter_in(_txn, _scope, _c, _operations),
    do: {:error, {:validation, ["operations must be a non-empty list"]}}

  defp alter_op(txn, scope, c, %{"op" => "add_field", "field" => spec}) do
    with {:ok, field} <- Schema.normalize_field(spec),
         :ok <- field_absent(c, field["name"]),
         {:ok, targets} <-
           reference_targets(txn, scope, c.name, c.table, %{"fields" => [field]}),
         {:ok, rows} <- SQL.scalar(txn, ~s[SELECT COUNT(*) FROM "#{c.table}"], []),
         :ok <- required_backfill_ok(field, rows),
         {:ok, _} <-
           SQL.exec(txn, ~s[ALTER TABLE "#{c.table}" ADD COLUMN #{column_sql(field, targets)}], []),
         :ok <- backfill_default(txn, c, field, rows) do
      schema = %{c.schema | "fields" => c.schema["fields"] ++ [field]}

      schema =
        cond do
          field["unique"] ->
            ensure_new_index(schema, [field["name"]], true)

          field["index"] or field["type"] == "reference" ->
            ensure_new_index(schema, [field["name"]], false)

          true ->
            schema
        end

      with :ok <- create_new_indexes(txn, c, schema) do
        {:ok, %{c | schema: schema}}
      end
    end
  end

  defp alter_op(txn, _scope, c, %{"op" => "drop_field", "name" => name} = op) do
    with :ok <- confirmed(op, "drop_field"),
         {:ok, field} <- fetch_field(c, name),
         :ok <- droppable(c, field) do
      text = Schema.text_fields(c.schema) -- [name]
      semantic = Schema.semantic_fields(c.schema) -- [name]
      single = Enum.filter(c.schema["indexes"], &(&1["fields"] == [name]))

      with {:ok, c} <- replace_search(txn, c, text, semantic),
           :ok <-
             SQL.exec_all(
               txn,
               Enum.map(single, &~s[DROP INDEX IF EXISTS "#{c.table}__#{&1["name"]}"])
             ),
           {:ok, _} <-
             SQL.exec(txn, ~s[ALTER TABLE "#{c.table}" DROP COLUMN #{Schema.column(name)}], []) do
        schema = %{
          c.schema
          | "fields" => Enum.reject(c.schema["fields"], &(&1["name"] == name)),
            "indexes" => c.schema["indexes"] -- single
        }

        {:ok, %{c | schema: schema}}
      end
    end
  end

  defp alter_op(_txn, _scope, c, %{"op" => "set_default", "name" => name} = op) do
    with {:ok, field} <- fetch_field(c, name) do
      case op["default"] do
        nil ->
          {:ok, put_field(c, Map.delete(field, "default"))}

        default ->
          with {:ok, updated} <- Schema.normalize_field(Map.put(field, "default", default)) do
            {:ok, put_field(c, Map.put(field, "default", updated["default"]))}
          end
      end
    end
  end

  defp alter_op(txn, _scope, c, %{"op" => "set_required", "name" => name, "required" => required})
       when is_boolean(required) do
    with {:ok, field} <- fetch_field(c, name) do
      cond do
        required and field["type"] == "reference" and field["on_delete"] == "set_null" ->
          {:error,
           {:validation, ["field #{name}: a required reference cannot use on_delete set_null"]}}

        required ->
          case SQL.scalar(
                 txn,
                 ~s[SELECT COUNT(*) FROM "#{c.table}" WHERE #{Schema.column(name)} IS NULL],
                 []
               ) do
            {:ok, 0} -> {:ok, put_field(c, Map.put(field, "required", true))}
            {:ok, n} -> {:error, {:validation, ["field #{name}: #{n} records have no value"]}}
            error -> error
          end

        true ->
          {:ok, put_field(c, Map.put(field, "required", false))}
      end
    end
  end

  defp alter_op(txn, _scope, c, %{"op" => "add_index"} = op) do
    with {:ok, schema} <- Schema.add_index(c.schema, Map.drop(op, ["op"])),
         :ok <- create_new_indexes(txn, c, schema) do
      {:ok, %{c | schema: schema}}
    end
  end

  defp alter_op(txn, _scope, c, %{"op" => "drop_index", "name" => name}) do
    case Enum.find(c.schema["indexes"], &(&1["name"] == name)) do
      nil ->
        {:error, {:not_found, "index_not_found"}}

      %{"fields" => [field]} = index ->
        cond do
          field == c.schema["owner_field"] ->
            {:error, {:validation, ["the owner field index cannot be dropped"]}}

          match?(%{"type" => "reference"}, Schema.field(c.schema, field)) and not index["unique"] ->
            {:error, {:validation, ["reference field indexes cannot be dropped"]}}

          true ->
            drop_index(txn, c, index)
        end

      index ->
        drop_index(txn, c, index)
    end
  end

  defp alter_op(txn, _scope, c, %{"op" => "set_search"} = op) do
    text = Map.get(op, "text", Schema.text_fields(c.schema))
    semantic = Map.get(op, "semantic", Schema.semantic_fields(c.schema))

    with {:ok, _schema} <- Schema.put_search(c.schema, %{"text" => text, "semantic" => semantic}) do
      replace_search(txn, c, text, semantic)
    end
  end

  defp alter_op(_txn, _scope, c, %{"op" => "set_owner_field", "name" => nil} = op) do
    with :ok <- confirmed(op, "set_owner_field") do
      {:ok, %{c | schema: Map.put(c.schema, "owner_field", nil)}}
    end
  end

  defp alter_op(txn, _scope, c, %{"op" => "set_owner_field", "name" => name}) do
    with {:ok, schema} <- Schema.put_owner_field(c.schema, name),
         :ok <- create_new_indexes(txn, c, schema) do
      {:ok, %{c | schema: schema}}
    end
  end

  defp alter_op(_txn, _scope, _c, op) do
    {:error, {:validation, ["unknown or incomplete alter operation: #{inspect(op["op"] || op)}"]}}
  end

  defp field_absent(c, name) do
    if Schema.field(c.schema, name),
      do: {:error, {:conflict, "field_exists", %{"field" => name}}},
      else: :ok
  end

  defp fetch_field(c, name) do
    case is_binary(name) && Schema.field(c.schema, name) do
      %{} = field -> {:ok, field}
      _ -> {:error, {:not_found, "field_not_found"}}
    end
  end

  defp put_field(c, field) do
    fields = Enum.map(c.schema["fields"], &if(&1["name"] == field["name"], do: field, else: &1))
    %{c | schema: %{c.schema | "fields" => fields}}
  end

  defp required_backfill_ok(%{"required" => true} = field, rows) when rows > 0 do
    if Map.has_key?(field, "default"),
      do: :ok,
      else:
        {:error,
         {:validation,
          [
            "field #{field["name"]}: a required field needs a default when the collection has records"
          ]}}
  end

  defp required_backfill_ok(_field, _rows), do: :ok

  defp backfill_default(_txn, _c, _field, 0), do: :ok

  defp backfill_default(txn, c, %{"default" => default} = field, _rows) do
    value =
      if field["type"] == "datetime" and default == "now",
        do: Schema.now(),
        else: elem(Schema.coerce(field, default), 1)

    case SQL.exec(txn, ~s[UPDATE "#{c.table}" SET #{Schema.column(field["name"])} = ?], [value]) do
      {:ok, _} -> :ok
      error -> error
    end
  end

  defp backfill_default(_txn, _c, _field, _rows), do: :ok

  defp droppable(c, field) do
    name = field["name"]

    composite =
      Enum.filter(c.schema["indexes"], &(name in &1["fields"] and length(&1["fields"]) > 1))

    cond do
      name == c.schema["owner_field"] ->
        {:error,
         {:validation, ["field #{name} is the owner field; clear it with set_owner_field first"]}}

      field["type"] == "reference" ->
        {:error,
         {:validation, ["reference fields cannot be dropped; create a new collection and migrate"]}}

      composite != [] ->
        {:error,
         {:validation,
          [
            "field #{name} is part of index #{Enum.map_join(composite, ", ", & &1["name"])}; drop it first"
          ]}}

      true ->
        :ok
    end
  end

  defp confirmed(%{"confirm" => true}, _op), do: :ok

  defp confirmed(_op, name),
    do: {:error, {:validation, ["#{name} is destructive and needs \"confirm\": true"]}}

  defp ensure_new_index(schema, fields, unique) do
    {:ok, schema} = Schema.add_index(schema, %{"fields" => fields, "unique" => unique})
    schema
  end

  # Creates every index declared in `schema` that the table does not have yet.
  defp create_new_indexes(txn, c, schema) do
    existing = MapSet.new(c.schema["indexes"], & &1["name"])
    new = Enum.reject(schema["indexes"], &MapSet.member?(existing, &1["name"]))

    case create_indexes(txn, c.table, new) do
      :ok ->
        :ok

      {:error, message} when is_binary(message) ->
        if String.contains?(message, "UNIQUE"),
          do: {:error, {:conflict, "unique_index_duplicates", %{}}},
          else: {:error, message}

      error ->
        error
    end
  end

  defp drop_index(txn, c, index) do
    with {:ok, _} <- SQL.exec(txn, ~s[DROP INDEX IF EXISTS "#{c.table}__#{index["name"]}"], []) do
      {:ok, %{c | schema: %{c.schema | "indexes" => c.schema["indexes"] -- [index]}}}
    end
  end

  defp replace_search(txn, c, text, semantic) do
    old_text = Schema.text_fields(c.schema)
    old_semantic = Schema.semantic_fields(c.schema)

    with :ok <- if(old_text == text, do: :ok, else: drop_fts(txn, c.table)),
         :ok <- if(old_text == text, do: :ok, else: create_fts(txn, c.table, text)),
         :ok <- clear_embeddings(txn, c, old_semantic == semantic) do
      {:ok, %{c | schema: Map.put(c.schema, "search", %{"text" => text, "semantic" => semantic})}}
    end
  end

  defp clear_embeddings(_txn, _c, true), do: :ok

  defp clear_embeddings(txn, c, false) do
    case SQL.exec(txn, "DELETE FROM data_embeddings WHERE collection_id = ?", [c.id]) do
      {:ok, _} -> :ok
      error -> error
    end
  end

  # ---------------------------------------------------------------------------
  # Drop
  # ---------------------------------------------------------------------------

  @doc """
  Drops a collection and its records. `confirm` must equal the collection
  name. Refused while another collection references it.
  """
  @spec drop(Scope.t(), String.t(), term()) :: :ok | {:error, term()}
  def drop(%Scope{} = scope, name, confirm) do
    with :ok <- Scope.allow_admin(scope) do
      case Store.transaction(fn txn -> drop_in(txn, scope, name, confirm) end) do
        {:ok, _} -> :ok
        error -> error
      end
    end
  end

  @doc false
  @spec drop_in(term(), Scope.t(), String.t(), term()) :: {:ok, t()} | {:error, term()}
  def drop_in(txn, scope, name, confirm) do
    with :ok <-
           if(confirm == name,
             do: :ok,
             else:
               {:error, {:validation, ["dropping a collection needs confirm equal to its name"]}}
           ),
         {:ok, c} <- load(txn, scope, name),
         {:ok, all} <- load_all(txn, scope),
         :ok <- unreferenced(c, all),
         :ok <- drop_fts(txn, c.table),
         :ok <-
           SQL.exec_all(txn, [
             ~s[DROP TABLE "#{c.table}"],
             {"DELETE FROM data_files WHERE collection_id = ?", [c.id]},
             {"DELETE FROM data_embeddings WHERE collection_id = ?", [c.id]},
             {"DELETE FROM data_collections WHERE id = ?", [c.id]}
           ]),
         :ok <- log_change(txn, scope, c, "drop", nil, nil, nil, %{"action" => "drop"}) do
      {:ok, c}
    end
  end

  defp unreferenced(c, all) do
    referrers =
      for other <- all,
          other.id != c.id,
          field <- other.schema["fields"],
          field["type"] == "reference" and field["references"] == c.name,
          do: "#{other.name}.#{field["name"]}"

    if referrers == [],
      do: :ok,
      else: {:error, {:conflict, "collection_referenced", %{"referenced_by" => referrers}}}
  end

