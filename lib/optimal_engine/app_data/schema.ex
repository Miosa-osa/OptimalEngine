defmodule OptimalEngine.AppData.Schema do
  @moduledoc """
  Collection definitions for app data: field types, constraints, indexes,
  the owner field and search fields, plus value coercion between JSON and
  the collection's SQLite columns.

  Every SQL identifier the app-data layer emits is derived here from a
  validated name (`^[a-z][a-z0-9_]{0,62}$`) with a fixed prefix and double
  quotes, or generated by the Engine. Values are always bound parameters.

  Field types and their storage:

  | Type | Column | JSON value |
  | --- | --- | --- |
  | `string` | TEXT | string, default max 4,096 characters |
  | `text` | TEXT | string, default max 1,000,000 characters |
  | `integer` | INTEGER | 64-bit integer |
  | `float` | REAL | number |
  | `boolean` | INTEGER 0/1 | true/false |
  | `datetime` | TEXT, UTC ISO 8601 with milliseconds | ISO 8601 string |
  | `json` | TEXT | any JSON value |
  | `reference` | TEXT, foreign key to another collection's `id` | record id |
  """

  @types ~w(string text integer float boolean datetime json reference)
  @on_delete ~w(restrict set_null cascade)
  @identifier ~r/^[a-z][a-z0-9_]{0,62}$/
  @record_id ~r/^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$/
  # System fields, and the filter combinators a field name would shadow.
  @reserved ~w(id version created_at updated_at created_by updated_by and or not)

  @max_fields 200
  @max_indexes 32
  @max_index_fields 8
  @max_search_fields 16
  @string_max 4_096
  @text_max 1_000_000

  @system_fields %{
    "id" => {~s("id"), "string"},
    "version" => {~s("_version"), "integer"},
    "created_at" => {~s("_created_at"), "datetime"},
    "updated_at" => {~s("_updated_at"), "datetime"},
    "created_by" => {~s("_created_by"), "string"},
    "updated_by" => {~s("_updated_by"), "string"}
  }

  @doc "Field types a collection may declare."
  @spec types() :: [String.t()]
  def types, do: @types

  @doc "System fields every record has, usable in filters and sorts."
  @spec system_fields() :: [String.t()]
  def system_fields, do: Map.keys(@system_fields)

  @doc "True for a valid collection, field, or index name."
  @spec identifier?(term()) :: boolean()
  def identifier?(name), do: is_binary(name) and Regex.match?(@identifier, name)

  @doc "True for a valid client-supplied record id."
  @spec record_id?(term()) :: boolean()
  def record_id?(id), do: is_binary(id) and Regex.match?(@record_id, id)

  @doc "The quoted column for a declared field."
  @spec column(String.t()) :: String.t()
  def column(name), do: ~s("f_#{name}")

  @doc "The quoted column and type for a system field, or nil."
  @spec system_field(String.t()) :: {String.t(), String.t()} | nil
  def system_field(name), do: Map.get(@system_fields, name)

  @doc "The SQLite column type for a field type."
  @spec sql_type(String.t()) :: String.t()
  def sql_type(type) when type in ~w(integer boolean), do: "INTEGER"
  def sql_type("float"), do: "REAL"
  def sql_type(_type), do: "TEXT"

  @doc "The field definition named `name`, or nil."
  @spec field(map(), String.t()) :: map() | nil
  def field(schema, name), do: Enum.find(schema["fields"], &(&1["name"] == name))

  @doc "Names of the declared fields, in declaration order."
  @spec field_names(map()) :: [String.t()]
  def field_names(schema), do: Enum.map(schema["fields"], & &1["name"])

  @doc "Fields indexed for full-text search."
  @spec text_fields(map()) :: [String.t()]
  def text_fields(schema), do: get_in(schema, ["search", "text"]) || []

  @doc "Fields embedded for semantic search."
  @spec semantic_fields(map()) :: [String.t()]
  def semantic_fields(schema), do: get_in(schema, ["search", "semantic"]) || []

  # ---------------------------------------------------------------------------
  # Definitions
  # ---------------------------------------------------------------------------

  @doc """
  Validates and normalizes a collection definition:

      %{"name" => "tasks",
        "fields" => [%{"name" => "title", "type" => "string", "required" => true}],
        "indexes" => [%{"fields" => ["owner", "due"]}],
        "owner_field" => "owner",
        "search" => %{"text" => ["title"], "semantic" => ["title"]}}

  `fields` may also be a map of name to field definition. Returns
  `{:ok, definition}` or `{:error, {:validation, [message]}}`. Whether
  referenced collections exist is checked by the caller.
  """
  @spec normalize_definition(term()) :: {:ok, map()} | {:error, {:validation, [String.t()]}}
  def normalize_definition(%{} = body) do
    name = body["name"]

    with :ok <- check(identifier?(name), "name must match #{inspect(Regex.source(@identifier))}"),
         {:ok, fields} <- normalize_fields(body["fields"]),
         schema = %{"fields" => fields, "indexes" => [], "owner_field" => nil, "search" => %{}},
         {:ok, schema} <- put_owner_field(schema, body["owner_field"]),
         {:ok, schema} <- put_search(schema, body["search"] || %{}),
         {:ok, schema} <- add_declared_indexes(schema, body["indexes"] || []) do
      {:ok, Map.put(schema, "name", name)}
    end
  end

  def normalize_definition(_body), do: invalid("collection definition must be an object")

  @doc "Validates one field definition (also used by `add_field`)."
  @spec normalize_field(term()) :: {:ok, map()} | {:error, {:validation, [String.t()]}}
  def normalize_field(%{} = spec) do
    name = spec["name"]
    type = spec["type"]

    errors =
      []
      |> add_error(not identifier?(name), "field name #{inspect(name)} is not a valid identifier")
      |> add_error(name in @reserved, "field name #{inspect(name)} is reserved")
      |> add_error(
        type not in @types,
        "field #{inspect(name)}: type must be one of #{Enum.join(@types, ", ")}"
      )

    if errors != [] do
      {:error, {:validation, Enum.reverse(errors)}}
    else
      field = %{
        "name" => name,
        "type" => type,
        "required" => spec["required"] == true,
        "unique" => spec["unique"] == true,
        "index" => spec["index"] == true
      }

      with {:ok, field} <- put_max_length(field, spec["max_length"]),
           {:ok, field} <- put_enum(field, spec["enum"]),
           {:ok, field} <- put_reference(field, spec),
           {:ok, field} <- put_default(field, Map.fetch(spec, "default")) do
        unique_ok = not (field["unique"] and type in ~w(json text))
        check_result(unique_ok, field, "field #{name}: #{type} fields cannot be unique")
      end
    end
  end

  def normalize_field(_spec), do: invalid("each field must be an object")

  defp normalize_fields(fields) when is_map(fields) and not is_struct(fields) do
    fields
    |> Enum.sort_by(fn {name, _spec} -> name end)
    |> Enum.map(fn
      {name, %{} = spec} -> Map.put(spec, "name", name)
      {name, type} when is_binary(type) -> %{"name" => name, "type" => type}
      {name, _} -> %{"name" => name}
    end)
    |> normalize_fields()
  end

  defp normalize_fields(fields) when is_list(fields) and fields != [] do
    if length(fields) > @max_fields do
      invalid("a collection may declare at most #{@max_fields} fields")
    else
      results = Enum.map(fields, &normalize_field/1)

      case for({:error, {:validation, errors}} <- results, do: errors) |> List.flatten() do
        [] ->
          normalized = for {:ok, field} <- results, do: field
          names = Enum.map(normalized, & &1["name"])

          if length(Enum.uniq(names)) == length(names),
            do: {:ok, normalized},
            else: invalid("field names must be unique")

        errors ->
          {:error, {:validation, errors}}
      end
    end
  end

  defp normalize_fields(_fields), do: invalid("fields must be a non-empty list or object")

  defp put_max_length(%{"type" => type} = field, nil) when type in ~w(string text),
    do: {:ok, Map.put(field, "max_length", default_max(type))}

  defp put_max_length(%{"type" => type} = field, max)
       when type in ~w(string text) and is_integer(max) and max > 0 do
    if max <= default_max(type),
      do: {:ok, Map.put(field, "max_length", max)},
      else: invalid("field #{field["name"]}: max_length may not exceed #{default_max(type)}")
  end

  defp put_max_length(field, nil), do: {:ok, field}

  defp put_max_length(field, _max),
    do:
      invalid(
        "field #{field["name"]}: max_length needs a string or text field and a positive integer"
      )

  defp default_max("string"), do: @string_max
  defp default_max("text"), do: @text_max

  defp put_enum(field, nil), do: {:ok, field}

  defp put_enum(%{"type" => "string"} = field, values) when is_list(values) and values != [] do
    if Enum.all?(values, &is_binary/1) and length(values) <= 256,
      do: {:ok, Map.put(field, "enum", Enum.uniq(values))},
      else: invalid("field #{field["name"]}: enum must list up to 256 strings")
  end

  defp put_enum(field, _values),
    do: invalid("field #{field["name"]}: enum needs a string field and a non-empty list")

  defp put_reference(%{"type" => "reference"} = field, spec) do
    target = spec["references"]
    on_delete = spec["on_delete"] || "restrict"

    cond do
      not identifier?(target) ->
        invalid("field #{field["name"]}: references must name a collection")

      on_delete not in @on_delete ->
        invalid("field #{field["name"]}: on_delete must be one of #{Enum.join(@on_delete, ", ")}")

      on_delete == "set_null" and field["required"] ->
        invalid("field #{field["name"]}: a required reference cannot use on_delete set_null")

      true ->
        {:ok, Map.merge(field, %{"references" => target, "on_delete" => on_delete})}
    end
  end

  defp put_reference(field, spec) do
    if Map.has_key?(spec, "references"),
      do: invalid("field #{field["name"]}: only reference fields may declare references"),
      else: {:ok, field}
  end

  defp put_default(field, :error), do: {:ok, field}
  defp put_default(field, {:ok, nil}), do: {:ok, field}

  defp put_default(%{"type" => "datetime"} = field, {:ok, "now"}),
    do: {:ok, Map.put(field, "default", "now")}

  defp put_default(%{"type" => "reference"} = field, {:ok, _value}),
    do: invalid("field #{field["name"]}: reference fields cannot have a default")

  defp put_default(field, {:ok, value}) do
    case coerce(field, value) do
      {:ok, _db_value} -> {:ok, Map.put(field, "default", normalize_json_value(field, value))}
      {:error, message} -> invalid("field #{field["name"]}: default #{message}")
    end
  end

  # Stored defaults are kept in their JSON form; datetimes are normalized.
  defp normalize_json_value(%{"type" => "datetime"}, value) do
    {:ok, normalized} = normalize_datetime(value)
    normalized
  end

  defp normalize_json_value(%{"type" => "float"}, value), do: value / 1
  defp normalize_json_value(_field, value), do: value

  @doc "Sets the owner field; it must be a declared string or reference field."
  @spec put_owner_field(map(), term()) :: {:ok, map()} | {:error, {:validation, [String.t()]}}
  def put_owner_field(schema, nil), do: {:ok, schema}

  def put_owner_field(schema, name) do
    case is_binary(name) && field(schema, name) do
      %{"type" => type} when type in ~w(string reference) ->
        {:ok, schema |> Map.put("owner_field", name) |> ensure_index([name], false)}

      _ ->
        invalid("owner_field must name a declared string or reference field")
    end
  end

  @doc "Sets the full-text and semantic search fields."
  @spec put_search(map(), term()) :: {:ok, map()} | {:error, {:validation, [String.t()]}}
  def put_search(schema, %{} = search) do
    text = search["text"] || []
    semantic = search["semantic"] || []

    with :ok <- check_search_fields(schema, text, "text"),
         :ok <- check_search_fields(schema, semantic, "semantic") do
      {:ok,
       Map.put(schema, "search", %{"text" => Enum.uniq(text), "semantic" => Enum.uniq(semantic)})}
    end
  end

  def put_search(_schema, _search), do: invalid("search must be an object")

  defp check_search_fields(schema, names, kind) do
    cond do
      not is_list(names) or length(names) > @max_search_fields ->
        invalid("search.#{kind} must list up to #{@max_search_fields} fields")

      Enum.all?(names, &match?(%{"type" => t} when t in ~w(string text), field(schema, &1))) ->
        :ok

      true ->
        invalid("search.#{kind} fields must be declared string or text fields")
    end
  end

  defp add_declared_indexes(schema, indexes) when is_list(indexes) do
    schema =
      Enum.reduce(schema["fields"], schema, fn field, acc ->
        cond do
          field["unique"] ->
            ensure_index(acc, [field["name"]], true)

          field["index"] or field["type"] == "reference" ->
            ensure_index(acc, [field["name"]], false)

          true ->
            acc
        end
      end)

    Enum.reduce_while(indexes, {:ok, schema}, fn spec, {:ok, acc} ->
      case add_index(acc, spec) do
        {:ok, acc} -> {:cont, {:ok, acc}}
        error -> {:halt, error}
      end
    end)
  end

  defp add_declared_indexes(_schema, _indexes), do: invalid("indexes must be a list")

  @doc """
  Adds a declared index `%{"fields" => [...], "unique" => bool, "name" => name}`.
  Returns `{:ok, schema}`; an identical index already declared is a no-op.
  """
  @spec add_index(map(), term()) :: {:ok, map()} | {:error, {:validation, [String.t()]}}
  def add_index(schema, %{"fields" => fields} = spec) when is_list(fields) do
    unique = spec["unique"] == true
    name = spec["name"]

    cond do
      fields == [] or length(fields) > @max_index_fields ->
        invalid("an index needs 1 to #{@max_index_fields} fields")

      length(Enum.uniq(fields)) != length(fields) ->
        invalid("index fields must be distinct")

      not Enum.all?(fields, &indexable?(schema, &1)) ->
        invalid("index fields must be declared fields other than json and text")

      name != nil and not identifier?(name) ->
        invalid("index name must be a valid identifier")

      name != nil and Enum.any?(schema["indexes"], &(&1["name"] == name)) ->
        invalid("an index named #{name} already exists")

      length(schema["indexes"]) >= @max_indexes ->
        invalid("a collection may declare at most #{@max_indexes} indexes")

      true ->
        {:ok, ensure_index(schema, fields, unique, name)}
    end
  end

  def add_index(_schema, _spec), do: invalid("an index needs a fields list")

  defp indexable?(schema, name) do
    case field(schema, name) do
      %{"type" => type} -> type not in ~w(json text)
      nil -> false
    end
  end

  defp ensure_index(schema, fields, unique, name \\ nil) do
    exists? = Enum.any?(schema["indexes"], &(&1["fields"] == fields and &1["unique"] == unique))

    if exists? do
      schema
    else
      name = name || index_name(fields, unique)
      index = %{"name" => name, "fields" => fields, "unique" => unique}
      Map.update!(schema, "indexes", &(&1 ++ [index]))
    end
  end

  defp index_name(fields, unique) do
    prefix = if unique, do: "u", else: "i"
    hash = :crypto.hash(:sha256, Enum.join(fields, ",")) |> Base.encode16(case: :lower)
    prefix <> "_" <> String.slice(hash, 0, 12)
  end

  # ---------------------------------------------------------------------------
  # Values
  # ---------------------------------------------------------------------------

  @doc """
  Coerces a JSON value to the column value for `field`. `nil` passes
  (required-ness is checked separately). Returns `{:ok, value}` or
  `{:error, message}`.
  """
  @spec coerce(map(), term()) :: {:ok, term()} | {:error, String.t()}
  def coerce(_field, nil), do: {:ok, nil}

  def coerce(%{"type" => type} = field, value) when type in ~w(string text) and is_binary(value) do
    cond do
      String.length(value) > field["max_length"] ->
        {:error, "is longer than #{field["max_length"]} characters"}

      is_list(field["enum"]) and value not in field["enum"] ->
        {:error, "must be one of #{Enum.join(field["enum"], ", ")}"}

      true ->
        {:ok, value}
    end
  end

  def coerce(%{"type" => "reference"}, value) when is_binary(value) do
    if record_id?(value), do: {:ok, value}, else: {:error, "is not a valid record id"}
  end

  def coerce(%{"type" => "integer"}, value)
      when is_integer(value) and value >= -9_223_372_036_854_775_808 and
             value <= 9_223_372_036_854_775_807,
      do: {:ok, value}

  def coerce(%{"type" => "float"}, value) when is_number(value), do: {:ok, value / 1}
  def coerce(%{"type" => "boolean"}, true), do: {:ok, 1}
  def coerce(%{"type" => "boolean"}, false), do: {:ok, 0}

  def coerce(%{"type" => "datetime"}, value) when is_binary(value) do
    case normalize_datetime(value) do
      {:ok, normalized} -> {:ok, normalized}
      :error -> {:error, "is not an ISO 8601 date or datetime"}
    end
  end

  def coerce(%{"type" => "json"}, value), do: {:ok, Jason.encode!(value)}
  def coerce(%{"type" => type}, _value), do: {:error, "must be a #{type}"}

  @doc "Converts a column value back to its JSON form."
  @spec decode(map() | String.t(), term()) :: term()
  def decode(_field, nil), do: nil
  def decode(%{"type" => "boolean"}, value), do: value == 1
  def decode(%{"type" => "json"}, value), do: Jason.decode!(value)
  def decode(%{"type" => "float"}, value) when is_integer(value), do: value / 1
  def decode(_field, value), do: value

  @doc """
  Normalizes an ISO 8601 date or datetime to a fixed-width UTC string with
  milliseconds (`2026-01-31T09:30:00.000Z`) so string order is time order.
  A bare date means midnight UTC. A datetime without an offset is UTC.
  """
  @spec normalize_datetime(String.t()) :: {:ok, String.t()} | :error
  def normalize_datetime(value) when is_binary(value) do
    with :error <- parse_datetime(value),
         :error <- parse_naive(value) do
      parse_date(value)
    end
  end

  def normalize_datetime(_value), do: :error

  defp parse_datetime(value) do
    case DateTime.from_iso8601(value) do
      {:ok, dt, _offset} -> {:ok, format_datetime(dt)}
      _ -> :error
    end
  end

  defp parse_naive(value) do
    case NaiveDateTime.from_iso8601(value) do
      {:ok, naive} -> {:ok, naive |> DateTime.from_naive!("Etc/UTC") |> format_datetime()}
      _ -> :error
    end
  end

  defp parse_date(value) do
    case Date.from_iso8601(value) do
      {:ok, date} -> {:ok, date |> DateTime.new!(~T[00:00:00], "Etc/UTC") |> format_datetime()}
      _ -> :error
    end
  end

  @doc "Formats a DateTime as a fixed-width UTC millisecond string."
  @spec format_datetime(DateTime.t()) :: String.t()
  def format_datetime(%DateTime{} = dt) do
    {microsecond, _precision} = dt.microsecond
    dt = DateTime.shift_zone!(dt, "Etc/UTC")
    millis = div(microsecond, 1000) * 1000
    %{dt | microsecond: {millis, 3}} |> DateTime.to_iso8601()
  end

  @doc "The current time as a fixed-width UTC millisecond string."
  @spec now() :: String.t()
  def now, do: format_datetime(DateTime.utc_now())

  # ---------------------------------------------------------------------------

  defp check(true, _message), do: :ok
  defp check(_false, message), do: invalid(message)

  defp check_result(true, value, _message), do: {:ok, value}
  defp check_result(false, _value, message), do: invalid(message)

  defp add_error(errors, true, message), do: [message | errors]
  defp add_error(errors, _false, _message), do: errors

  defp invalid(message), do: {:error, {:validation, [message]}}
end
