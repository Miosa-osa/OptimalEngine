  @doc """
  Brings the PostgreSQL schema in line with the derived plan, then checks the
  live catalog against it.

  Options: `:schema`, the PostgreSQL schema (default `public`); the pool must
  have been started with the same schema.

  Returns a report of what was done. `changed: false` means the recorded
  fingerprint already matched and the catalog matched the plan.
  """
  @spec sync(GenServer.server(), keyword()) :: {:ok, map()} | {:error, term()}
  def sync(pool, opts \\ []) do
    with {:ok, plan} <- derive(),
         {:ok, schema} <- Connection.schema(opts) do
      locked(pool, plan, schema)
    end
  end

  @doc """
  Compares the live catalog of `schema` with the plan and returns every
  difference, without changing anything.
  """
  @spec drift(GenServer.server(), keyword()) :: {:ok, [String.t()]} | {:error, term()}
  def drift(pool, opts \\ []) do
    with {:ok, plan} <- derive(),
         {:ok, schema} <- Connection.schema(opts) do
      Postgrex.transaction(pool, fn conn -> differences(conn, plan, schema) end, timeout: 300_000)
    end
  rescue
    error in [Postgrex.Error, DBConnection.ConnectionError] -> {:error, Errors.message(error)}
  end

  defp locked(pool, plan, schema) do
    result =
      Postgrex.transaction(
        pool,
        fn conn ->
          # Read committed, so the reads after the lock see what an engine that
          # held the lock before this one committed.
          required!(conn, "SET TRANSACTION ISOLATION LEVEL READ COMMITTED")
          required!(conn, "SET LOCAL statement_timeout = '300s'")
          required!(conn, "SET LOCAL lock_timeout = '300s'")

          required!(conn, "SELECT pg_advisory_xact_lock(hashtext($1), hashtext($2))", [
            @lock_namespace,
            schema
          ])

          if schema != "public",
            do: required!(conn, "CREATE SCHEMA IF NOT EXISTS #{quote_name(schema)}")

          in_schema!(conn, schema)

          required!(
            conn,
            "CREATE TABLE IF NOT EXISTS #{@meta_table} (key TEXT PRIMARY KEY, value TEXT NOT NULL)"
          )

          state = state(conn, plan, schema)

          if state.fingerprint == plan.fingerprint and state.versions == plan.versions and
               differences(conn, plan, schema) == [] do
            %{changed: false, fingerprint: plan.fingerprint, skipped: plan.skipped}
          else
            apply_plan(conn, plan, schema, state)
          end
        end,
        timeout: 300_000
      )

    case result do
      {:ok, report} ->
        log_report(report)
        {:ok, report}

      {:error, reason} ->
        {:error, reason}
    end
  rescue
    error in [Postgrex.Error, DBConnection.ConnectionError] ->
      {:error, Errors.message(error)}
  end

  # The pool's search_path decides where every statement lands; a pool started
  # for another schema would apply the plan in the wrong place.
  defp in_schema!(conn, schema) do
    case select!(conn, "SELECT current_schema()", []) do
      [[^schema]] ->
        :ok

      [[other]] ->
        Postgrex.rollback(conn, {:schema, "the pool's schema is #{inspect(other)}, not #{schema}"})
    end
  end

  defp state(conn, plan, schema) do
    tables = live_tables(conn, schema)

    versions =
      if MapSet.member?(tables, "schema_migrations"),
        do:
          conn
          |> select!("SELECT version FROM schema_migrations ORDER BY version", [])
          |> Enum.map(&hd/1),
        else: []

    meta = conn |> select!("SELECT key, value FROM #{@meta_table}", []) |> Map.new(&List.to_tuple/1)

    %{
      tables: tables,
      versions: versions,
      fresh?: versions == [] and not Enum.any?(plan.tables, &MapSet.member?(tables, &1.name)),
      fingerprint: meta["fingerprint"],
      owned_indexes: meta |> Map.get("indexes", "") |> String.split("\n", trim: true)
    }
  end

  defp apply_plan(conn, plan, schema, state) do
    pending = plan.versions -- state.versions
    check_versions!(conn, plan, state, pending)

    created =
      for table <- plan.tables, not MapSet.member?(state.tables, table.name) do
        required!(conn, create_table(table))
        table.name
      end

    columns = live_columns(conn, schema)

    added =
      for table <- plan.tables,
          MapSet.member?(state.tables, table.name),
          column <- table.columns,
          not Map.has_key?(columns, {table.name, column.name}) do
        required!(
          conn,
          "ALTER TABLE #{quote_name(table.name)} ADD COLUMN IF NOT EXISTS #{column_definition(column)}"
        )

        "#{table.name}.#{column.name}"
      end

    dropped = drop_unplanned(conn, plan, schema, state)
    steps = if state.fresh?, do: [], else: run_steps(conn, pending)

    create_objects(conn, plan, schema)
    view_notes = Enum.map(plan.views, &create_view(conn, &1))

    if state.fresh? do
      # Seeds go in table creation order, and a later migration can point an
      # earlier table at a later one; every key is checked at commit instead.
      required!(conn, "SET CONSTRAINTS ALL DEFERRED")
      Enum.each(plan.seeds, &seed(conn, &1, plan.tables))
    else
      record_versions(conn, plan, pending)
    end

    put_meta(conn, "fingerprint", plan.fingerprint)
    put_meta(conn, "indexes", plan.indexes |> Enum.map(& &1.name) |> Enum.join("\n"))

    case differences(conn, plan, schema) do
      [] -> :ok
      drift -> Postgrex.rollback(conn, {:schema_drift, drift})
    end

    %{
      changed: true,
      fresh: state.fresh?,
      fingerprint: plan.fingerprint,
      created_tables: created,
      added_columns: added,
      dropped_objects: dropped,
      steps: steps,
      recorded_versions: if(state.fresh?, do: plan.versions, else: pending),
      skipped: plan.skipped ++ Enum.reject(view_notes, &is_nil/1)
    }
  end

  defp check_versions!(conn, plan, state, pending) do
    newer = state.versions -- plan.versions
    below = Enum.filter(pending, &(&1 <= Steps.baseline()))

    cond do
      newer != [] ->
        Postgrex.rollback(conn, {:schema_newer, newer})

      state.fresh? ->
        :ok

      state.versions == [] ->
        Postgrex.rollback(
          conn,
          {:schema_drift, ["the store's tables exist but no migration versions are recorded"]}
        )

      below != [] ->
        Postgrex.rollback(
          conn,
          {:schema_drift, ["versions at or below the baseline are not recorded: #{inspect(below)}"]}
        )

      true ->
        :ok
    end
  end

  defp run_steps(conn, pending) do
    for version <- Enum.sort(pending),
        step = Steps.for_version(version),
        is_list(step),
        {label, sql} <- step do
      required!(conn, sql)
      "#{version} #{label}"
    end
  end

  # Checks, foreign keys and unique indexes decide which writes succeed, so on
  # the store's tables only the plan's may exist. A plain index is dropped
  # only when an earlier sync created it.
  defp drop_unplanned(conn, plan, schema, state) do
    tables = MapSet.new(plan.tables, & &1.name)
    planned = planned_objects(plan)
    constraints = live_constraints(conn, schema)
    indexes = live_indexes(conn, schema)

    # Foreign keys go first: one can depend on a unique key dropped after it.
    unplanned_constraints =
      Enum.sort_by(
        for {{table, name}, type} <- constraints,
            MapSet.member?(tables, table),
            not MapSet.member?(planned.constraints, {table, name}) do
          {type, table, name}
        end,
        fn {type, _table, _name} -> if type == "f", do: 0, else: 1 end
      )

    owned = MapSet.new(state.owned_indexes)

    unplanned_indexes =
      for {{table, name}, %{unique: unique, constraint: false}} <- indexes,
          MapSet.member?(tables, table),
          not MapSet.member?(planned.indexes, {table, name}),
          unique or MapSet.member?(owned, name) do
        name
      end

    Enum.each(unplanned_constraints, fn {_type, table, name} ->
      required!(conn, "ALTER TABLE #{quote_name(table)} DROP CONSTRAINT #{quote_name(name)}")
    end)

    Enum.each(unplanned_indexes, &required!(conn, "DROP INDEX IF EXISTS #{quote_name(&1)}"))

    Enum.map(unplanned_constraints, fn {_type, table, name} -> "#{table}.#{name}" end) ++
      unplanned_indexes
  end

  defp create_objects(conn, plan, schema) do
    for table <- plan.tables, columns <- table.uniques do
      required!(conn, unique_index(table.name, columns))
    end

    Enum.each(plan.indexes, &required!(conn, &1.sql))

    existing = live_constraints(conn, schema)

    for table <- plan.tables,
        {name, sql} <- check_constraints(table) ++ foreign_key_constraints(table),
        not Map.has_key?(existing, {table.name, name}) do
      required!(conn, sql)
    end
  end

  defp planned_objects(plan) do
    indexes =
      Enum.flat_map(plan.tables, fn table ->
        Enum.map(table.uniques, &{table.name, unique_name(table.name, &1)})
      end) ++ Enum.map(plan.indexes, &{&1.table, &1.name})

    constraints =
      Enum.flat_map(plan.tables, fn table ->
        Enum.map(
          check_constraints(table) ++ foreign_key_constraints(table),
          &{table.name, elem(&1, 0)}
        )
      end)

    %{indexes: MapSet.new(indexes), constraints: MapSet.new(constraints)}
  end

  # A view whose columns changed cannot be replaced in place, so it is dropped
  # and created again; a view PostgreSQL rejects is reported, not fatal.
  defp create_view(conn, view) do
    name = quote_name(view.name)
    replace = "CREATE OR REPLACE VIEW #{name} AS #{view.sql}"

    with {:error, _} <- Postgrex.query(conn, replace, [], mode: :savepoint),
         nil <- optional(conn, :view, view.name, "DROP VIEW IF EXISTS #{name}") do
      optional(conn, :view, view.name, "CREATE VIEW #{name} AS #{view.sql}")
    else
      {:ok, _} -> nil
      %{} = note -> note
    end
  end

  defp seed(conn, %{table: name, columns: columns, rows: rows}, tables) do
    placeholders = Enum.map_join(1..length(columns), ", ", &"$#{&1}")

    insert =
      "INSERT INTO #{quote_name(name)} (#{Enum.map_join(columns, ", ", &quote_name/1)}) " <>
        "VALUES (#{placeholders})"

    Enum.each(rows, &required!(conn, insert, &1))

    table = Enum.find(tables, &(&1.name == name))

    for %{identity: true, name: column} <- table.columns do
      required!(
        conn,
        "SELECT setval(pg_get_serial_sequence($1, $2), " <>
          "COALESCE((SELECT MAX(#{quote_name(column)}) FROM #{quote_name(name)}), 0) + 1, false)",
        [quote_name(name), column]
      )
    end
  end

  # A database that already exists records the versions it reaches now, with
  # the description the migration carries; the seed rows are not inserted again.
  defp record_versions(conn, plan, pending) do
    %{columns: columns, rows: rows} = Enum.find(plan.seeds, &(&1.table == "schema_migrations"))
    description = Enum.find_index(columns, &(&1 == "description"))

    for version <- pending,
        row = Enum.find(rows, &(hd(&1) == version)) do
      required!(
        conn,
        "INSERT INTO schema_migrations (version, description) VALUES ($1, $2) ON CONFLICT DO NOTHING",
        [version, description && Enum.at(row, description)]
      )
    end
  end

  defp put_meta(conn, key, value) do
    required!(
      conn,
      "INSERT INTO #{@meta_table} (key, value) VALUES ($1, $2) " <>
        "ON CONFLICT (key) DO UPDATE SET value = excluded.value",
      [key, value]
    )
  end

  # ---------------------------------------------------------------------------
  # Comparing the catalog with the plan
  # ---------------------------------------------------------------------------

  defp differences(conn, plan, schema) do
    tables = live_tables(conn, schema)
    columns = live_columns(conn, schema)
    keys = live_primary_keys(conn, schema)
    defaults = expected_defaults(conn, plan)
    planned = planned_objects(plan)
    indexes = live_indexes(conn, schema)
    constraints = live_constraints(conn, schema)
    plan_tables = MapSet.new(plan.tables, & &1.name)

    plan_columns =
      for table <- plan.tables, column <- table.columns, into: MapSet.new() do
        {table.name, column.name}
      end

    table_drift =
      Enum.flat_map(plan.tables, fn table ->
        if MapSet.member?(tables, table.name) do
          column_drift(table, columns, defaults) ++ key_drift(table, keys)
        else
          ["table #{table.name} is missing"]
        end
      end)

    extra_columns =
      for {{table, column}, _live} <- columns,
          MapSet.member?(plan_tables, table),
          not MapSet.member?(plan_columns, {table, column}) do
        "column #{table}.#{column} is not in the schema"
      end

    missing_indexes =
      for {table, name} <- planned.indexes, not Map.has_key?(indexes, {table, name}) do
        "index #{name} on #{table} is missing"
      end

    missing_constraints =
      for {table, name} <- planned.constraints, not Map.has_key?(constraints, {table, name}) do
        "constraint #{name} on #{table} is missing"
      end

    extra_constraints =
      for {{table, name}, _type} <- constraints,
          MapSet.member?(plan_tables, table),
          not MapSet.member?(planned.constraints, {table, name}) do
        "constraint #{name} on #{table} is not in the schema"
      end

    extra_uniques =
      for {{table, name}, %{unique: true, constraint: false}} <- indexes,
          MapSet.member?(plan_tables, table),
          not MapSet.member?(planned.indexes, {table, name}) do
        "unique index #{name} on #{table} is not in the schema"
      end

    recorded =
      if MapSet.member?(tables, "schema_migrations"),
        do:
          conn
          |> select!("SELECT version FROM schema_migrations ORDER BY version", [])
          |> Enum.map(&hd/1),
        else: []

    versions =
      if recorded == plan.versions,
        do: [],
        else: [
          "recorded versions differ: missing #{inspect(plan.versions -- recorded)}, extra #{inspect(recorded -- plan.versions)}"
        ]

    Enum.sort(
      extra_columns ++ missing_indexes ++ missing_constraints ++ extra_constraints ++ extra_uniques
    ) ++
      table_drift ++ versions
  end

  defp column_drift(table, columns, defaults) do
    Enum.flat_map(table.columns, fn column ->
      name = "#{table.name}.#{column.name}"

      case Map.fetch(columns, {table.name, column.name}) do
        :error ->
          ["column #{name} is missing"]

        {:ok, live} ->
          expected = expected_column(table, column, defaults)

          for {field, want} <- expected, Map.fetch!(live, field) != want do
            "column #{name}: #{field} is #{inspect(Map.fetch!(live, field))}, expected #{inspect(want)}"
          end
      end
    end)
  end

  defp expected_column(table, column, defaults) do
    {type, collation} =
      case column.type do
        @text -> {"text", "C"}
        "BIGINT" -> {"bigint", nil}
        "DOUBLE PRECISION" -> {"double precision", nil}
        "BYTEA" -> {"bytea", nil}
      end

    %{
      type: type,
      collation: collation,
      not_null: column.not_null or column.identity or column.name in table.primary_key,
      identity: if(column.identity, do: "d", else: ""),
      default:
        if(column.identity or is_nil(column.default),
          do: nil,
          else: Map.fetch!(defaults, {column.type, column.default})
        )
    }
  end

  defp key_drift(table, keys) do
    live = Map.get(keys, table.name, [])

    if live == table.primary_key,
      do: [],
      else: [
        "primary key of #{table.name} is #{inspect(live)}, expected #{inspect(table.primary_key)}"
      ]
  end

  # PostgreSQL stores a default in its own normalised form. Each expected
  # default goes through the same normalisation on a temporary table, so the
  # live default can be compared as text.
  defp expected_defaults(conn, plan) do
    pairs =
      plan.tables
      |> Enum.flat_map(& &1.columns)
      |> Enum.reject(&(&1.identity or is_nil(&1.default)))
      |> Enum.map(&{&1.type, &1.default})
      |> Enum.uniq()

    if pairs == [] do
      %{}
    else
      definitions =
        pairs
        |> Enum.with_index(1)
        |> Enum.map_join(", ", fn {{type, default}, index} ->
          ~s("c#{index}" #{type} DEFAULT #{default})
        end)

      required!(conn, "DROP TABLE IF EXISTS pg_temp.#{@probe_table}")
      required!(conn, "CREATE TEMP TABLE #{@probe_table} (#{definitions}) ON COMMIT DROP")

      normalised =
        conn
        |> select!(
          """
          SELECT a.attnum, pg_get_expr(d.adbin, d.adrelid)
          FROM pg_attrdef d
          JOIN pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum
          WHERE d.adrelid = 'pg_temp.#{@probe_table}'::regclass
          """,
          []
        )
        |> Map.new(fn [index, expression] -> {index, expression} end)

      required!(conn, "DROP TABLE pg_temp.#{@probe_table}")

      pairs
      |> Enum.with_index(1)
      |> Map.new(fn {pair, index} -> {pair, Map.fetch!(normalised, index)} end)
    end
  end

  defp live_tables(conn, schema) do
    conn
    |> select!(
      """
      SELECT c.relname FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = $1 AND c.relkind IN ('r', 'p')
      """,
      [schema]
    )
    |> MapSet.new(&hd/1)
  end

  defp live_columns(conn, schema) do
    conn
    |> select!(
      """
      SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod), co.collname::text,
             a.attnotnull, a.attidentity::text, pg_get_expr(d.adbin, d.adrelid)
      FROM pg_attribute a
      JOIN pg_class c ON c.oid = a.attrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      LEFT JOIN pg_collation co ON co.oid = a.attcollation AND a.attcollation <> 0
      LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE n.nspname = $1 AND c.relkind IN ('r', 'p') AND a.attnum > 0 AND NOT a.attisdropped
      """,
      [schema]
    )
    |> Map.new(fn [table, column, type, collation, not_null, identity, default] ->
      {{table, column},
       %{
         type: type,
         collation: collation,
         not_null: not_null in [true, 1],
         identity: identity,
         default: default
       }}
    end)
  end

  defp live_primary_keys(conn, schema) do
    conn
    |> select!(
      """
      SELECT c.relname, a.attname
      FROM pg_index i
      JOIN pg_class c ON c.oid = i.indrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      CROSS JOIN LATERAL unnest(i.indkey::int2[]) WITH ORDINALITY AS k(attnum, ord)
      JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = k.attnum
      WHERE n.nspname = $1 AND i.indisprimary
      ORDER BY c.relname, k.ord
      """,
      [schema]
    )
    |> Enum.group_by(&hd/1, &List.last/1)
  end

  defp live_indexes(conn, schema) do
    conn
    |> select!(
      """
      SELECT t.relname, ic.relname, i.indisunique,
             EXISTS (
               SELECT 1 FROM pg_constraint c
               WHERE c.conindid = i.indexrelid AND c.conrelid = i.indrelid
                 AND c.contype IN ('p', 'u', 'x')
             )
      FROM pg_index i
      JOIN pg_class ic ON ic.oid = i.indexrelid
      JOIN pg_class t ON t.oid = i.indrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
      WHERE n.nspname = $1
      """,
      [schema]
    )
    |> Map.new(fn [table, name, unique, constraint] ->
      {{table, name}, %{unique: unique in [true, 1], constraint: constraint in [true, 1]}}
    end)
  end

  defp live_constraints(conn, schema) do
    conn
    |> select!(
      """
      SELECT t.relname, c.conname, c.contype::text
      FROM pg_constraint c
      JOIN pg_class t ON t.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
      WHERE n.nspname = $1 AND c.contype IN ('c', 'f', 'u', 'x')
      """,
      [schema]
    )
    |> Map.new(fn [table, name, type] -> {{table, name}, type} end)
  end

  defp required!(conn, sql, params \\ []) do
    case Postgrex.query(conn, sql, params) do
      {:ok, result} -> result
      {:error, error} -> Postgrex.rollback(conn, {:schema, Errors.message(error), sql})
    end
  end

  defp select!(conn, sql, params), do: required!(conn, sql, params).rows

  # A statement PostgreSQL rejects is rolled back to its savepoint and
  # reported; the transaction goes on.
  defp optional(conn, kind, name, sql) do
    case Postgrex.query(conn, sql, [], mode: :savepoint) do
      {:ok, _} -> nil
      {:error, error} -> %{kind: kind, name: name, reason: Errors.message(error)}
    end
  end

  defp log_report(%{changed: false}), do: :ok

  defp log_report(report) do
    Logger.info(
      "[Store.Postgres] schema applied: #{length(report.created_tables)} tables created, " <>
        "#{length(report.added_columns)} columns added, #{length(report.dropped_objects)} objects dropped, " <>
        "#{length(report.steps)} data steps, #{length(report.skipped)} objects skipped"
    )
  end

  # ---------------------------------------------------------------------------
  # SQLite helpers
  # ---------------------------------------------------------------------------

  defp rows(db, sql, params \\ []) do
    {:ok, statement} = Exqlite.Sqlite3.prepare(db, sql)

    try do
      :ok = Exqlite.Sqlite3.bind(statement, params)
      collect(db, statement, [])
    after
      Exqlite.Sqlite3.release(db, statement)
    end
  end

  defp collect(db, statement, acc) do
    case Exqlite.Sqlite3.step(db, statement) do
      {:row, row} -> collect(db, statement, [row | acc])
      :done -> Enum.reverse(acc)
      {:error, reason} -> raise "schema introspection failed: #{inspect(reason)}"
    end
  end

  defp upcase(nil), do: ""
  defp upcase(text), do: text |> String.trim() |> String.upcase()
end
