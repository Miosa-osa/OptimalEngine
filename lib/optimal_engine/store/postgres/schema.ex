  @doc """
  The PostgreSQL plan for the schema this build's migrations produce, or an
  error naming everything that has no translation.

  The plan is derived once per node and kept in `:persistent_term`.
  """
  @spec derive() :: {:ok, plan()} | {:error, term()}
  def derive do
    case :persistent_term.get({__MODULE__, :plan}, nil) do
      nil ->
        with :ok <- Steps.check(),
             {:ok, plan} <- derive_in_memory(),
             :ok <- complete(plan) do
          :persistent_term.put({__MODULE__, :plan}, plan)
          {:ok, plan}
        end

      plan ->
        {:ok, plan}
    end
  end

  @doc "The notes that leave a plan incomplete."
  @spec fatal_notes(plan()) :: [note()]
  def fatal_notes(plan), do: Enum.filter(plan.notes, &(&1.kind in @fatal_kinds))

  defp complete(plan) do
    case fatal_notes(plan) do
      [] -> :ok
      notes -> {:error, {:untranslatable_schema, notes}}
    end
  end

  @doc """
  The identity column of each table that has one, kept in `:persistent_term`.
  Empty when the schema cannot be derived, since no store then starts.
  """
  @spec identity_columns() :: %{String.t() => String.t()}
  def identity_columns do
    case :persistent_term.get({__MODULE__, :identity}, nil) do
      nil ->
        columns =
          case derive() do
            {:ok, plan} ->
              for table <- plan.tables,
                  %{identity: true, name: column} <- table.columns,
                  into: %{} do
                {table.name, column}
              end

            {:error, _reason} ->
              %{}
          end

        :persistent_term.put({__MODULE__, :identity}, columns)
        columns

      columns ->
        columns
    end
  end

  # The migrations log every step; deriving the plan is not a migration of the
  # engine's store, so it runs quietly in its own process.
  defp derive_in_memory do
    task =
      Task.async(fn ->
        Logger.put_process_level(self(), :error)

        with {:ok, db} <- Exqlite.Sqlite3.open(":memory:") do
          try do
            with :ok <- OptimalEngine.Store.SQLite.migrate(db) do
              {:ok, from_sqlite(db)}
            end
          rescue
            error -> {:error, {:derive_failed, Exception.message(error)}}
          after
            Exqlite.Sqlite3.close(db)
          end
        end
      end)

    Task.await(task, 120_000)
  end

  @doc "The PostgreSQL plan for the schema of an open SQLite database."
  @spec from_sqlite(Exqlite.Sqlite3.db()) :: plan()
  def from_sqlite(db) do
    objects =
      rows(db, """
      SELECT m.name, l.type, l.wr, m.sql
      FROM sqlite_master m
      JOIN pragma_table_list l ON l.name = m.name AND l.schema = 'main'
      WHERE m.type IN ('table', 'view') AND m.name NOT LIKE 'sqlite\\_%' ESCAPE '\\'
      ORDER BY m.rowid
      """)

    derived =
      for [name, "table", without_rowid, sql] <- objects do
        table(db, name, without_rowid == 1, sql)
      end

    tables = Enum.map(derived, &elem(&1, 0))
    table_names = MapSet.new(tables, & &1.name)
    tables = Enum.map(tables, &resolve_foreign_keys(&1, tables))

    full_text =
      for [name, type, _wr, _sql] <- objects, type in ["virtual", "shadow"], into: MapSet.new() do
        name
      end

    {indexes, index_notes} = indexes(db, table_names)
    {views, view_notes} = views(objects)
    {trigger_skips, trigger_notes} = triggers(db, full_text)
    {seeds, seed_notes} = seeds(db, tables)

    skipped =
      for [name, type, _wr, _sql] <- objects, type in ["virtual", "shadow"] do
        %{
          kind: :table,
          name: name,
          reason: "#{type} table (FTS5); full-text search is not on PostgreSQL"
        }
      end ++ trigger_skips

    notes =
      Enum.flat_map(derived, &elem(&1, 1)) ++
        foreign_key_notes(tables) ++
        index_notes ++
        view_notes ++ trigger_notes ++ seed_notes ++ identifier_notes(tables, indexes, views)

    plan = %{
      tables: tables,
      indexes: indexes,
      views: views,
      seeds: seeds,
      versions: versions(seeds),
      skipped: skipped,
      notes: notes
    }

    Map.put(plan, :fingerprint, fingerprint(plan))
  end

  defp table(db, name, without_rowid, sql) do
    info =
      rows(
        db,
        ~s|SELECT name, type, "notnull", dflt_value, pk FROM pragma_table_info(?1) ORDER BY cid|,
        [name]
      )

    primary_key =
      info
      |> Enum.filter(fn [_name, _type, _notnull, _default, pk] -> pk > 0 end)
      |> Enum.sort_by(fn [_name, _type, _notnull, _default, pk] -> pk end)
      |> Enum.map(fn [column | _] -> column end)

    identity =
      case primary_key do
        [column] ->
          not without_rowid and
            Enum.any?(info, fn [n, type | _] -> n == column and upcase(type) == "INTEGER" end)

        _ ->
          false
      end

    {columns, column_notes} =
      Enum.map_reduce(info, [], fn [column, declared, notnull, default, _pk], notes ->
        {type, type_notes} = column_type(name, column, declared)
        {default, default_notes} = column_default(name, column, default, type)

        {%{
           name: column,
           type: type,
           not_null: notnull == 1,
           default: default,
           identity: identity and primary_key == [column]
         }, notes ++ type_notes ++ default_notes}
      end)

    {uniques, unique_notes} = uniques(db, name)
    {checks, check_notes} = checks(name, sql)

    table = %{
      name: name,
      columns: columns,
      primary_key: primary_key,
      uniques: uniques,
      checks: checks,
      foreign_keys: foreign_keys(db, name)
    }

    {table, column_notes ++ unique_notes ++ check_notes}
  end

  @doc """
  The PostgreSQL type for a declared SQLite column type, by SQLite's affinity
  rules. Returns `:unmapped` for a declared type with no rule here.
  """
  @spec postgres_type(String.t() | nil) :: String.t() | :unmapped
  def postgres_type(declared) do
    upper = upcase(declared)

    cond do
      upper == "" -> :unmapped
      String.contains?(upper, "INT") -> "BIGINT"
      String.contains?(upper, ["CHAR", "CLOB", "TEXT"]) -> @text
      String.contains?(upper, "BLOB") -> "BYTEA"
      String.contains?(upper, ["REAL", "FLOA", "DOUB"]) -> "DOUBLE PRECISION"
      upper in ["BOOLEAN", "BOOL"] -> "BIGINT"
      String.starts_with?(upper, ["NUMERIC", "DECIMAL"]) -> "DOUBLE PRECISION"
      String.starts_with?(upper, ["DATE", "TIME", "JSON"]) -> @text
      true -> :unmapped
    end
  end

  defp column_type(table, column, declared) do
    case postgres_type(declared) do
      :unmapped ->
        {@text,
         [
           %{
             kind: :column_type,
             name: "#{table}.#{column}",
             reason: "declared type #{inspect(declared)} has no mapping"
           }
         ]}

      type ->
        {type, []}
    end
  end

  @doc """
  The PostgreSQL default for a SQLite default expression and column type, or
  `nil` when the column has no default.
  """
  @spec postgres_default(String.t() | nil, String.t()) ::
          {:ok, String.t() | nil} | {:error, term()}
  def postgres_default(nil, _type), do: {:ok, nil}

  def postgres_default(expression, type) do
    case upcase(expression) do
      "NULL" -> {:ok, nil}
      "CURRENT_TIMESTAMP" -> {:ok, cast("datetime('now')", type)}
      "CURRENT_DATE" -> {:ok, cast("strftime('%Y-%m-%d', 'now')", type)}
      "TRUE" when type == "BIGINT" -> {:ok, cast("1", type)}
      "FALSE" when type == "BIGINT" -> {:ok, cast("0", type)}
      _ -> {:ok, cast(expression, type)}
    end
    |> case do
      {:ok, nil} -> {:ok, nil}
      {:ok, sqlite} -> Dialect.to_postgres(sqlite)
    end
  end

  # SQLite stores a default of another type through the column's affinity
  # (`TEXT DEFAULT 0` stores '0'); PostgreSQL needs the cast written out.
  defp cast(expression, type), do: "CAST((#{expression}) AS #{base_type(type)})"

  defp base_type(@text), do: "TEXT"
  defp base_type(type), do: type

  defp column_default(table, column, expression, type) do
    case postgres_default(expression, type) do
      {:ok, default} ->
        {default, []}

      {:error, reason} ->
        {nil,
         [
           %{
             kind: :column_default,
             name: "#{table}.#{column}",
             reason: "default #{expression} not translated: #{inspect(reason)}"
           }
         ]}
    end
  end

  defp uniques(db, table) do
    rows(db, "SELECT name FROM pragma_index_list(?1) WHERE origin = 'u' ORDER BY seq", [table])
    |> Enum.map_reduce([], fn [index], notes ->
      columns =
        rows(db, "SELECT name FROM pragma_index_info(?1) ORDER BY seqno", [index])
        |> Enum.map(&hd/1)

      if Enum.any?(columns, &is_nil/1) do
        note = %{kind: :unique, name: "#{table}.#{index}", reason: "expression unique key"}
        {nil, [note | notes]}
      else
        {columns, notes}
      end
    end)
    |> then(fn {uniques, notes} -> {Enum.reject(uniques, &is_nil/1), Enum.reverse(notes)} end)
  end

  defp checks(table, sql) do
    case check_clauses(sql) do
      {:ok, clauses} ->
        Enum.map_reduce(clauses, [], fn clause, notes ->
          case Dialect.to_postgres(clause) do
            {:ok, translated} ->
              {translated, notes}

            {:error, reason} ->
              {nil, notes ++ [%{kind: :check, name: table, reason: inspect(reason)}]}
          end
        end)
        |> then(fn {checks, notes} -> {Enum.reject(checks, &is_nil/1), notes} end)

      {:error, reason} ->
        {[], [%{kind: :check, name: table, reason: inspect(reason)}]}
    end
  end

  defp foreign_keys(db, table) do
    rows(
      db,
      ~s|SELECT id, seq, "table", "from", "to", on_update, on_delete FROM pragma_foreign_key_list(?1) ORDER BY id, seq|,
      [table]
    )
    |> Enum.group_by(&hd/1)
    |> Enum.sort_by(fn {id, _rows} -> id end)
    |> Enum.map(fn {id, rows} ->
      [[_id, _seq, parent, _from, _to, on_update, on_delete] | _] = rows

      %{
        id: id,
        columns: Enum.map(rows, &Enum.at(&1, 3)),
        table: parent,
        references: Enum.map(rows, &Enum.at(&1, 4)),
        on_update: on_update,
        on_delete: on_delete
      }
    end)
  end

  # A foreign key that names no parent columns references the parent's
  # primary key.
  defp resolve_foreign_keys(table, tables) do
    keys =
      Enum.map(table.foreign_keys, fn key ->
        if Enum.all?(key.references, &is_nil/1) do
          parent = Enum.find(tables, &(&1.name == key.table))
          %{key | references: (parent && parent.primary_key) || key.references}
        else
          key
        end
      end)

    %{table | foreign_keys: keys}
  end

  defp foreign_key_notes(tables) do
    for table <- tables,
        key <- table.foreign_keys,
        key.references == [] or Enum.any?(key.references, &is_nil/1) do
      %{
        kind: :foreign_key,
        name: foreign_key_name(table.name, key),
        reason: "#{table.name} references #{key.table}, which has no primary key"
      }
    end
  end

  @index_header ~r/\A\s*CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?("(?:[^"]|"")+"|[A-Za-z_][A-Za-z0-9_$]*)\s+ON\s+(.*)\z/is

  defp indexes(db, table_names) do
    rows(
      db,
      "SELECT name, tbl_name, sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL ORDER BY rowid"
    )
    |> Enum.filter(fn [_name, table, _sql] -> MapSet.member?(table_names, table) end)
    |> Enum.map_reduce([], fn [name, table, sql], notes ->
      with {:ok, translated} <- Dialect.to_postgres(sql),
           [_, unique, _name, target] <- Regex.run(@index_header, translated) do
        definition = "#{String.upcase(unique)}INDEX ON #{target}"
        hashed = "#{String.slice(name, 0, 50)}_#{hash(definition)}"

        sql =
          "CREATE #{String.upcase(unique)}INDEX IF NOT EXISTS #{quote_name(hashed)} ON #{target}"

        {%{name: hashed, sqlite_name: name, table: table, unique: unique != "", sql: sql}, notes}
      else
        {:error, reason} ->
          {nil, notes ++ [%{kind: :index, name: name, reason: inspect(reason)}]}

        nil ->
          {nil, notes ++ [%{kind: :index, name: name, reason: "unrecognised index statement"}]}
      end
    end)
    |> then(fn {indexes, notes} -> {Enum.reject(indexes, &is_nil/1), notes} end)
  end

  @view_header ~r/\A\s*CREATE\s+(?:TEMP(?:ORARY)?\s+)?VIEW\s+(?:IF\s+NOT\s+EXISTS\s+)?\S+\s+AS\s+(.*)\z/is

  defp views(objects) do
    for [name, "view", _wr, sql] <- objects, reduce: {[], []} do
      {views, notes} ->
        with [_, select] <- Regex.run(@view_header, sql),
             {:ok, translated} <- Dialect.to_postgres(select) do
          {views ++ [%{name: name, sql: translated}], notes}
        else
          nil ->
            {views, notes ++ [%{kind: :view, name: name, reason: "unrecognised header"}]}

          {:error, reason} ->
            {views, notes ++ [%{kind: :view, name: name, reason: inspect(reason)}]}
        end
    end
  end

  # A trigger is skipped only when every table its body writes is a full-text
  # table the plan skips; any other trigger has no PostgreSQL counterpart here
  # and fails the derivation.
  defp triggers(db, full_text) do
    rows(db, "SELECT name, sql FROM sqlite_master WHERE type = 'trigger' ORDER BY rowid")
    |> Enum.reduce({[], []}, fn [name, sql], {skips, notes} ->
      written = written_tables(sql)

      if written != [] and Enum.all?(written, &MapSet.member?(full_text, &1)) do
        reason = "maintains the full-text table #{Enum.join(Enum.uniq(written), ", ")}"
        {skips ++ [%{kind: :trigger, name: name, reason: reason}], notes}
      else
        reason = "writes #{inspect(Enum.uniq(written))}; only full-text triggers are skipped"
        {skips, notes ++ [%{kind: :trigger, name: name, reason: reason}]}
      end
    end)
  end

  @doc false
  @spec written_tables(String.t()) :: [String.t()]
  def written_tables(sql) do
    case Regex.split(~r/\bBEGIN\b/i, sql, parts: 2) do
      [_header, body] ->
        ~r/\b(?:INSERT(?:\s+OR\s+\w+)?\s+INTO|REPLACE\s+INTO|UPDATE(?:\s+OR\s+\w+)?|DELETE\s+FROM)\s+("[^"]+"|[A-Za-z_][A-Za-z0-9_]*)/i
        |> Regex.scan(body, capture: :all_but_first)
        |> Enum.map(fn [table] -> String.trim(table, ~s(")) end)

      _ ->
        []
    end
  end

  # The rows the migrations leave in each table, inserted on a fresh database.
  # A seeded table needs a key, so the rows can be told apart from rows
  # written later.
  defp seeds(db, tables) do
    for table <- tables,
        columns = Enum.map(table.columns, & &1.name),
        select =
          "SELECT #{Enum.map_join(columns, ", ", &quote_name/1)} FROM #{quote_name(table.name)}",
        rows = rows(db, select),
        rows != [],
        reduce: {[], []} do
      {seeds, notes} ->
        notes =
          if table.primary_key == [] and table.uniques == [],
            do: notes ++ [%{kind: :seed, name: table.name, reason: "seeded table has no key"}],
            else: notes

        {seeds ++ [%{table: table.name, columns: columns, rows: rows}], notes}
    end
  end

  defp versions(seeds) do
    versions =
      for %{table: "schema_migrations", rows: rows} <- seeds, [version | _] <- rows, do: version

    Enum.sort(versions)
  end

  # PostgreSQL folds unquoted identifiers to lower case, and its reserved
  # words need quotes. The DDL quotes every name and the engine's statements do
  # not, so a name only works on both when it is a lower-case identifier that
  # is not reserved.
  defp identifier_notes(tables, indexes, views) do
    names =
      Enum.flat_map(tables, fn table ->
        [{table.name, table.name} | Enum.map(table.columns, &{"#{table.name}.#{&1.name}", &1.name})]
      end) ++ Enum.map(views, &{&1.name, &1.name})

    for {qualified, name} <- names, reason = identifier_problem(name), reason != nil do
      %{kind: :identifier, name: qualified, reason: reason}
    end ++
      for index <- indexes, byte_size(index.name) > 63 do
        %{kind: :identifier, name: index.name, reason: "longer than 63 bytes"}
      end
  end

  defp identifier_problem(name) do
    cond do
      not Regex.match?(@identifier, name) -> "not a lower-case identifier"
      name in @reserved -> "a PostgreSQL reserved word"
      byte_size(name) > 63 -> "longer than 63 bytes"
      true -> nil
    end
  end

  # The fingerprint is the DDL text the plan applies and the migration
  # versions it records. Seeded rows carry the time the in-memory schema was
  # built, so they are not part of it.
  defp fingerprint(plan) do
    (statements(plan) ++ Enum.map(plan.versions, &Integer.to_string/1))
    |> Enum.join("\n")
    |> then(&:crypto.hash(:sha256, &1))
    |> Base.encode16(case: :lower)
  end

  @doc "Every DDL statement the plan applies, in order."
  @spec statements(plan()) :: [String.t()]
  def statements(plan) do
    Enum.map(plan.tables, &create_table/1) ++
      Enum.flat_map(plan.tables, fn table ->
        Enum.map(table.uniques, &unique_index(table.name, &1))
      end) ++
      Enum.map(plan.indexes, & &1.sql) ++
      Enum.flat_map(plan.tables, fn table -> Enum.map(check_constraints(table), &elem(&1, 1)) end) ++
      Enum.flat_map(plan.tables, fn table ->
        Enum.map(foreign_key_constraints(table), &elem(&1, 1))
      end) ++
      Enum.map(plan.views, &"CREATE OR REPLACE VIEW #{quote_name(&1.name)} AS #{&1.sql}")
  end

  # ---------------------------------------------------------------------------
  # CHECK clauses
  # ---------------------------------------------------------------------------

  @doc """
  The expressions of every `CHECK (...)` clause in a `CREATE TABLE` statement,
  in order. Quoted text and identifiers are skipped, so a `CHECK` inside a
  literal is not a clause.
  """
  @spec check_clauses(String.t() | nil) :: {:ok, [String.t()]} | {:error, :unbalanced}
  def check_clauses(nil), do: {:ok, []}
  def check_clauses(sql), do: scan_checks(sql, nil, [])

  defp scan_checks(<<>>, _previous, found), do: {:ok, Enum.reverse(found)}

  defp scan_checks(<<quote, rest::binary>>, _previous, found) when quote in [?', ?"] do
    case take_quoted(rest, quote, []) do
      {:ok, _quoted, rest} -> scan_checks(rest, quote, found)
      :error -> {:error, :unbalanced}
    end
  end

  defp scan_checks(<<char, rest::binary>> = sql, previous, found) when char in [?C, ?c] do
    with false <- identifier_char?(previous),
         [prefix] <- Regex.run(~r/\ACHECK\s*\(/i, sql) do
      body = binary_part(sql, byte_size(prefix), byte_size(sql) - byte_size(prefix))

      case balanced(body, 1, []) do
        {:ok, expression, rest} -> scan_checks(rest, ?), [String.trim(expression) | found])
        :error -> {:error, :unbalanced}
      end
    else
      _ -> scan_checks(rest, char, found)
    end
  end

  defp scan_checks(<<char, rest::binary>>, _previous, found), do: scan_checks(rest, char, found)

  defp balanced(<<>>, _depth, _acc), do: :error

  defp balanced(<<quote, rest::binary>>, depth, acc) when quote in [?', ?"] do
    case take_quoted(rest, quote, [quote]) do
      {:ok, quoted, rest} -> balanced(rest, depth, [quoted | acc])
      :error -> :error
    end
  end

  defp balanced(<<?(, rest::binary>>, depth, acc), do: balanced(rest, depth + 1, [?( | acc])

  defp balanced(<<?), rest::binary>>, 1, acc),
    do: {:ok, acc |> Enum.reverse() |> IO.iodata_to_binary(), rest}

  defp balanced(<<?), rest::binary>>, depth, acc), do: balanced(rest, depth - 1, [?) | acc])
  defp balanced(<<char, rest::binary>>, depth, acc), do: balanced(rest, depth, [char | acc])

  # A doubled quote inside quoted text is an escaped quote.
  defp take_quoted(<<>>, _quote, _acc), do: :error

  defp take_quoted(<<quote, quote, rest::binary>>, quote, acc),
    do: take_quoted(rest, quote, [quote, quote | acc])

  defp take_quoted(<<quote, rest::binary>>, quote, acc),
    do: {:ok, [quote | acc] |> Enum.reverse() |> IO.iodata_to_binary(), rest}

  defp take_quoted(<<char, rest::binary>>, quote, acc), do: take_quoted(rest, quote, [char | acc])

  defp identifier_char?(nil), do: false

  defp identifier_char?(char),
    do: char in ?a..?z or char in ?A..?Z or char in ?0..?9 or char == ?_

