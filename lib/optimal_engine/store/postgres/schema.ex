  @doc "The `CREATE TABLE` statement for one table of the plan."
  @spec create_table(table()) :: String.t()
  def create_table(table) do
    columns = Enum.map(table.columns, &column_definition/1)

    primary_key =
      case table.primary_key do
        [] -> []
        keys -> ["PRIMARY KEY (#{Enum.map_join(keys, ", ", &quote_name/1)})"]
      end

    "CREATE TABLE IF NOT EXISTS #{quote_name(table.name)} (\n  " <>
      Enum.join(columns ++ primary_key, ",\n  ") <> "\n)"
  end

  defp column_definition(%{identity: true} = column) do
    "#{quote_name(column.name)} BIGINT GENERATED BY DEFAULT AS IDENTITY"
  end

  defp column_definition(column) do
    [
      quote_name(column.name),
      column.type,
      if(column.not_null, do: "NOT NULL"),
      if(column.default, do: "DEFAULT #{column.default}")
    ]
    |> Enum.reject(&is_nil/1)
    |> Enum.join(" ")
  end

  @doc "The unique index that enforces one unique key."
  @spec unique_index(String.t(), [String.t()]) :: String.t()
  def unique_index(table, columns) do
    "CREATE UNIQUE INDEX IF NOT EXISTS #{quote_name(unique_name(table, columns))} " <>
      "ON #{quote_name(table)} (#{Enum.map_join(columns, ", ", &quote_name/1)})"
  end

  defp unique_name(table, columns), do: object_name("uq", table, Enum.join(columns, "\0"))

  defp check_constraints(table) do
    for expression <- table.checks do
      name = object_name("ck", table.name, expression)

      {name,
       "ALTER TABLE #{quote_name(table.name)} ADD CONSTRAINT #{quote_name(name)} CHECK (#{expression})"}
    end
  end

  defp foreign_key_constraints(table) do
    for key <- table.foreign_keys do
      name = foreign_key_name(table.name, key)

      {name,
       "ALTER TABLE #{quote_name(table.name)} ADD CONSTRAINT #{quote_name(name)} " <>
         "FOREIGN KEY (#{Enum.map_join(key.columns, ", ", &quote_name/1)}) " <>
         "REFERENCES #{quote_name(key.table)} (#{Enum.map_join(key.references, ", ", &quote_name(to_string(&1)))}) " <>
         "ON DELETE #{key.on_delete} ON UPDATE #{key.on_update} DEFERRABLE INITIALLY IMMEDIATE"}
    end
  end

  defp foreign_key_name(table, key) do
    definition =
      Enum.join(
        [
          Enum.join(key.columns, ","),
          key.table,
          Enum.map_join(key.references, ",", &to_string/1),
          key.on_delete,
          key.on_update
        ],
        "\0"
      )

    object_name("fk", table, definition)
  end

  # PostgreSQL truncates names to 63 bytes; the hash of the definition keeps
  # two long names apart and changes when the definition does.
  defp object_name(prefix, table, definition),
    do: "#{prefix}_#{String.slice(table, 0, 48)}_#{hash(table <> "\0" <> definition)}"

  defp hash(text) do
    :crypto.hash(:sha256, text) |> Base.encode16(case: :lower) |> binary_part(0, 8)
  end

  defp quote_name(name), do: ~s("#{String.replace(name, ~s("), ~s(""))}")

