defmodule OptimalEngine.Store.Postgres.Schema do
  @moduledoc """
  The PostgreSQL schema of the canonical store, derived from the schema the
  engine's own SQLite migrations produce.

  There is one schema definition: the SQLite migrations. `derive/0` runs them
  against an in-memory SQLite database, reads the result back through SQLite's
  catalog (`pragma_table_list`, `pragma_table_info`, `pragma_index_list`,
  `pragma_foreign_key_list`) and builds the PostgreSQL definition from it, so a
  migration written for SQLite reaches PostgreSQL without a second schema to
  keep in step. A new migration is picked up by the next build.

  ## Mapping

  | SQLite | PostgreSQL |
  | --- | --- |
  | `INTEGER PRIMARY KEY` (the rowid alias) | `BIGINT GENERATED BY DEFAULT AS IDENTITY` |
  | INTEGER affinity, `BOOLEAN` | `BIGINT` |
  | TEXT affinity, `DATE`, `DATETIME`, `TIME`, `TIMESTAMP`, `JSON` | `TEXT COLLATE "C"` |
  | REAL affinity, `NUMERIC`, `DECIMAL` | `DOUBLE PRECISION` |
  | `BLOB` | `BYTEA` |
  | `UNIQUE` | a unique index named for its columns |
  | `CHECK` | a check constraint named for its expression |
  | `FOREIGN KEY` | a constraint named for its definition, `DEFERRABLE INITIALLY IMMEDIATE` |
  | `CREATE INDEX` | the same statement through the dialect, named for its definition |
  | `CREATE VIEW` | `CREATE OR REPLACE VIEW` through the dialect |
  | a default expression | the same expression through the dialect, cast to the column type |
  | rows the migrations insert | the same rows, on a fresh database |

  Text uses the `C` collation, so text sorts and compares byte by byte, as with
  SQLite's default `BINARY` collation, whatever the database's locale.

  Every index and constraint is named with a hash of its definition, so a
  migration that changes one produces a new name rather than an object that
  silently keeps the old definition.

  Not derived: FTS5 virtual tables, their shadow tables, and the triggers that
  maintain them. Each one is listed in the plan's `skipped` entries; full-text
  search is not available on the PostgreSQL store. A trigger that writes any
  other table is not skipped: the derivation fails.

  ## Failing loudly

  `derive/0` fails, and the store does not start, when anything in the SQLite
  schema has no translation: a column type, a default, a check, an index, a
  unique key on an expression, a foreign key to a table without a key, a name
  PostgreSQL folds or reserves, a trigger, or seeded rows in a table without a
  key. It also fails when a migration above the baseline has a data statement
  with no declared PostgreSQL step (`OptimalEngine.Store.Postgres.Steps`). A
  view PostgreSQL cannot run is reported, not fatal.

  ## Applying

  `sync/2` runs in one transaction under an advisory lock, so engines starting
  together against one database apply it once:

  1. A database with no recorded migration versions and none of the tables is
     fresh. It is created in the derived shape and gets the rows the
     migrations insert, once.
  2. Otherwise the versions the database lacks are its pending versions. Their
     tables and columns are added, the declared steps of each pending version
     run, and the versions are recorded. Seed rows are never inserted again.
  3. Indexes and constraints are brought to the plan: a missing one is
     created, a check, foreign key or unique index the plan does not have is
     dropped, and so is an index an earlier sync created that the plan no
     longer has. An index the plan does not know and no sync created is left
     alone. Any rejection fails the sync.
  4. The live catalog is compared with the plan: every table, column (type,
     collation, `NOT NULL`, identity, default), primary key, index, check and
     foreign key, and the recorded versions. Any difference rolls the sync back
     with `{:error, {:schema_drift, differences}}`.

  The fingerprint of the derived DDL is recorded in `optimal_store_schema`; an
  unchanged fingerprint skips straight to the comparison, and a failed
  comparison applies the plan again before it gives up. A database that
  records a version this build does not have is refused with
  `{:error, {:schema_newer, versions}}`.
  """

  require Logger

  alias OptimalEngine.Store.Dialect
  alias OptimalEngine.Store.Postgres.{Connection, Errors, Steps}

  @text ~s(TEXT COLLATE "C")
  @identifier ~r/\A[a-z_][a-z0-9_]*\z/
  @lock_namespace "optimal_engine.store.schema"
  @meta_table "optimal_store_schema"
  @probe_table "optimal_store_default_probe"

  # PostgreSQL 16 keywords that cannot name a table or column without quotes
  # (reserved, and reserved but usable as a function or type name).
  @reserved ~w(
    all analyse analyze and any array as asc asymmetric both case cast check
    collate column constraint create current_catalog current_date current_role
    current_time current_timestamp current_user default deferrable desc distinct
    do else end except false fetch for foreign from grant group having in
    initially intersect into lateral leading limit localtime localtimestamp not
    null offset on only or order placing primary references returning select
    session_user some symmetric system_user table then to trailing true union
    unique user using variadic when where window with authorization binary
    collation concurrently cross current_schema freeze full ilike inner is
    isnull join left like natural notnull outer overlaps right similar
    tablesample verbose
  )

  # Notes that leave the schema incomplete. A view note is reported only.
  @fatal_kinds [
    :column_type,
    :column_default,
    :unique,
    :check,
    :foreign_key,
    :index,
    :identifier,
    :trigger,
    :seed
  ]

  @type column :: %{
          name: String.t(),
          type: String.t(),
          not_null: boolean(),
          default: String.t() | nil,
          identity: boolean()
        }

  @type table :: %{
          name: String.t(),
          columns: [column()],
          primary_key: [String.t()],
          uniques: [[String.t()]],
          checks: [String.t()],
          foreign_keys: [map()]
        }

  @type note :: %{kind: atom(), name: String.t(), reason: String.t()}

  @type plan :: %{
          tables: [table()],
          indexes: [
            %{
              name: String.t(),
              sqlite_name: String.t(),
              table: String.t(),
              unique: boolean(),
              sql: String.t()
            }
          ],
          views: [%{name: String.t(), sql: String.t()}],
          seeds: [%{table: String.t(), columns: [String.t()], rows: [[term()]]}],
          versions: [pos_integer()],
          skipped: [note()],
          notes: [note()],
          fingerprint: String.t()
        }

