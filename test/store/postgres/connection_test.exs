defmodule OptimalEngine.Store.Postgres.ConnectionTest do
  @moduledoc """
  The boundary where the engine's SQLite statements run on PostgreSQL:
  translation, parameter affinity, SQLite-shaped results and errors, the
  transaction contract, and serializable retries.

  Every statement in the parity block runs on an in-memory SQLite database and
  on PostgreSQL, and the rows must match.
  """

  use ExUnit.Case, async: false

  import ExUnit.CaptureLog

  alias OptimalEngine.Store.Postgres.Connection
  alias OptimalEngine.Test.PostgresStore

  @moduletag :postgres

  @items """
  CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT COLLATE "C" NOT NULL UNIQUE,
    n BIGINT,
    score DOUBLE PRECISION,
    data BYTEA,
    meta TEXT COLLATE "C",
    created_at TEXT COLLATE "C"
  )
  """

  @sqlite_items """
  CREATE TABLE items (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL UNIQUE,
    n INTEGER,
    score REAL,
    data BLOB,
    meta TEXT,
    created_at TEXT
  )
  """

  setup_all do
    schema = PostgresStore.unique_schema()
    pool = start_supervised!({Connection, PostgresStore.options(schema, pool_size: 6)})
    {:ok, _} = Connection.query(pool, ~s(CREATE SCHEMA "#{schema}"), [], dialect: :postgres)
    on_exit(fn -> PostgresStore.drop_schema(schema) end)
    %{pool: pool}
  end

  setup %{pool: pool} do
    {:ok, _} = Connection.query(pool, "DROP TABLE IF EXISTS items", [], dialect: :postgres)
    {:ok, _} = Connection.query(pool, @items, [], dialect: :postgres)
    :ok
  end

  defp query!(pool, sql, params \\ []) do
    {:ok, %{rows: rows}} = Connection.query(pool, sql, params)
    rows
  end

  describe "SQLite statements" do
    test "placeholders, INSERT OR IGNORE and datetime('now') run unchanged", %{pool: pool} do
      insert = "INSERT OR IGNORE INTO items (name, n, created_at) VALUES (?1, ?2, datetime('now'))"

      assert {:ok, %{num_rows: 1}} = Connection.query(pool, insert, ["a", 1])
      assert {:ok, %{num_rows: 0}} = Connection.query(pool, insert, ["a", 2])

      assert [["a", 1, created_at]] = query!(pool, "SELECT name, n, created_at FROM items")
      assert created_at =~ ~r/\A\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\z/
    end

    test "a construct the dialect refuses never reaches the database", %{pool: pool} do
      assert {:error, {:unsupported, "INSERT OR REPLACE"}} =
               Connection.query(pool, "INSERT OR REPLACE INTO items (name) VALUES (?1)", ["a"])
    end
  end

  describe "parameter affinity" do
    test "values bind the way SQLite stores them", %{pool: pool} do
      query!(
        pool,
        "INSERT INTO items (name, n, score, data, meta) VALUES (?1, ?2, ?3, ?4, ?5)",
        [7, "42", 3, {:blob, <<0, 1, 2, 0>>}, :tag]
      )

      assert [["7", 42, 3.0, <<0, 1, 2, 0>>, "tag"]] =
               query!(pool, "SELECT name, n, score, data, meta FROM items")

      assert [["7"]] = query!(pool, "SELECT name FROM items WHERE name = ?1", [7])
      assert [[1]] = query!(pool, "SELECT COUNT(*) FROM items WHERE n = ?1", ["42"])
    end

    test "a value no SQLite affinity accepts is an error, not a stored value", %{pool: pool} do
      assert {:error, message} =
               Connection.query(pool, "INSERT INTO items (name, n) VALUES (?1, ?2)", ["x", 1.5])

      assert message =~ "expected an integer"
      assert [] = query!(pool, "SELECT name FROM items")
    end

    test "aggregates and comparisons return SQLite's integers and floats", %{pool: pool} do
      for {name, n} <- [{"a", 1}, {"b", 2}, {"c", 4}] do
        query!(pool, "INSERT INTO items (name, n) VALUES (?1, ?2)", [name, n])
      end

      assert [[7, avg, 3, 1]] =
               query!(pool, "SELECT SUM(n), AVG(n), COUNT(*), MAX(n) > 3 FROM items")

      assert is_float(avg)
      assert_in_delta avg, 7 / 3, 1.0e-9
    end
  end

  describe "errors" do
    test "constraint and catalog errors read as SQLite's", %{pool: pool} do
      query!(pool, "INSERT INTO items (name) VALUES (?1)", ["a"])

      assert {:error, "UNIQUE constraint failed: items.name"} =
               Connection.query(pool, "INSERT INTO items (name) VALUES (?1)", ["a"])

      assert {:error, "NOT NULL constraint failed: items.name"} =
               Connection.query(pool, "INSERT INTO items (name) VALUES (NULL)")

      assert {:error, "no such table: missing_table"} =
               Connection.query(pool, "SELECT * FROM missing_table")

      assert {:error, "no such column: missing_column"} =
               Connection.query(pool, "SELECT missing_column FROM items")

      assert {:error, "duplicate column name: n"} =
               Connection.query(pool, "ALTER TABLE items ADD COLUMN n BIGINT", [],
                 dialect: :postgres
               )
    end
  end

  describe "refusals at the boundary" do
    test "a schema change in the engine's dialect is refused, whatever comments come first",
         %{pool: pool} do
      assert {:error, {:unsupported, "schema change outside the migrations"}} =
               Connection.query(pool, "CREATE TABLE extra (a INTEGER)")

      assert {:error, {:unsupported, "schema change outside the migrations"}} =
               Connection.query(pool, "  -- a comment\n  ALTER TABLE items ADD COLUMN x TEXT")

      assert {:error, {:unsupported, "schema change outside the migrations"}} =
               Connection.query(pool, "/* a note */ ; CREATE INDEX extra_name ON items (name)")
    end

    test "a transaction statement raises before it reaches the database, in either dialect",
         %{pool: pool} do
      for statement <- [
            "BEGIN",
            "COMMIT",
            "ROLLBACK",
            "SAVEPOINT s",
            "END",
            "/* x */ COMMIT",
            "START TRANSACTION",
            "ABORT"
          ],
          opts <- [[], [dialect: :postgres]] do
        assert_raise ArgumentError, ~r/Store.transaction/, fn ->
          Connection.query(pool, statement, [], opts)
        end
      end
    end

    test "inside a transaction a savepoint of the caller's own works as on SQLite",
         %{pool: pool} do
      insert = "INSERT INTO items (name) VALUES (?1)"

      assert {:ok, :done} =
               Connection.transaction(
                 pool,
                 fn txn ->
                   {:ok, _} = Connection.txn_query(txn, insert, ["kept"])
                   {:ok, _} = Connection.txn_query(txn, "SAVEPOINT attempt")
                   {:ok, _} = Connection.txn_query(txn, insert, ["undone"])
                   {:error, _} = Connection.txn_query(txn, insert, ["kept"])
                   {:ok, _} = Connection.txn_query(txn, "ROLLBACK TO attempt")
                   {:ok, _} = Connection.txn_query(txn, "RELEASE attempt")
                   {:ok, _} = Connection.txn_query(txn, "PRAGMA defer_foreign_keys = ON")

                   assert_raise ArgumentError, fn -> Connection.txn_query(txn, "/* x */ COMMIT") end
                   {:ok, _} = Connection.txn_query(txn, insert, ["after"])
                   {:ok, :done}
                 end,
                 5_000
               )

      assert [["after"], ["kept"]] = query!(pool, "SELECT name FROM items ORDER BY name")
    end

    test "a json_extract compared to a placeholder bound to a number is refused", %{pool: pool} do
      sql = "SELECT name FROM items WHERE json_extract(meta, '$.n') = ?1"

      assert {:error, {:unsupported, "json_extract compared to a non-text value"}} =
               Connection.query(pool, sql, [5])

      assert {:ok, %{rows: []}} = Connection.query(pool, sql, ["5"])
    end

    test "a timeout must be finite", %{pool: pool} do
      assert_raise ArgumentError, ~r/finite timeout/, fn ->
        Connection.query(pool, "SELECT 1", [], timeout: :infinity)
      end

      assert_raise ArgumentError, ~r/finite timeout/, fn ->
        Connection.transaction(pool, fn _txn -> {:ok, :never} end, :infinity)
      end
    end
  end

  describe "sessions" do
    test "every transaction runs serializable in the store's schema", %{pool: pool} do
      assert {:ok, [["serializable", _schema]]} =
               Connection.transaction(
                 pool,
                 fn txn ->
                   with {:ok, %{rows: rows}} <-
                          Connection.txn_query(
                            txn,
                            "SELECT current_setting('transaction_isolation'), current_schema()"
                          ),
                        do: {:ok, rows}
                 end,
                 5_000
               )
    end

    test "a connection in another schema or isolation is closed, not used", %{pool: pool} do
      log =
        capture_log(fn ->
          assert_raise RuntimeError, ~r/expected serializable with elsewhere/, fn ->
            DBConnection.run(pool, &Connection.verify_session!(&1, "elsewhere"))
          end
        end)

      assert log =~ "expected serializable with elsewhere"
    end

    test "each session has statement, lock and idle timeouts", %{pool: pool} do
      assert {:ok, %{rows: [["1min", "15s", "1min"]]}} =
               Connection.query(
                 pool,
                 "SELECT current_setting('statement_timeout'), current_setting('lock_timeout'), " <>
                   "current_setting('idle_in_transaction_session_timeout')"
               )
    end
  end

  describe "transactions" do
    test "commit on {:ok, _} and roll back on {:error, _}", %{pool: pool} do
      assert {:ok, :done} =
               Connection.transaction(
                 pool,
                 fn txn ->
                   {:ok, _} =
                     Connection.txn_query(txn, "INSERT INTO items (name) VALUES (?1)", ["a"])

                   {:ok, :done}
                 end,
                 5_000
               )

      assert {:error, :nope} =
               Connection.transaction(
                 pool,
                 fn txn ->
                   {:ok, _} =
                     Connection.txn_query(txn, "INSERT INTO items (name) VALUES (?1)", ["b"])

                   {:error, :nope}
                 end,
                 5_000
               )

      assert [["a"]] = query!(pool, "SELECT name FROM items")
    end

    test "any other return rolls back and is reported", %{pool: pool} do
      assert {:error, {:invalid_transaction_return, :weird}} =
               Connection.transaction(
                 pool,
                 fn txn ->
                   {:ok, _} =
                     Connection.txn_query(txn, "INSERT INTO items (name) VALUES (?1)", ["a"])

                   :weird
                 end,
                 5_000
               )

      assert [] = query!(pool, "SELECT name FROM items")
    end

    test "an exception in the fun rolls back and is raised in the caller", %{pool: pool} do
      assert_raise RuntimeError, "boom", fn ->
        Connection.transaction(
          pool,
          fn txn ->
            {:ok, _} = Connection.txn_query(txn, "INSERT INTO items (name) VALUES (?1)", ["a"])
            raise "boom"
          end,
          5_000
        )
      end

      assert [] = query!(pool, "SELECT name FROM items")
    end

    test "every way out of a transaction leaves its connection outside one" do
      schema = PostgresStore.unique_schema()
      {:ok, single} = Connection.start_link(PostgresStore.options(schema, pool_size: 1))

      on_exit(fn -> PostgresStore.drop_schema(schema) end)

      {:ok, _} =
        Connection.query(single, ~s(CREATE SCHEMA "#{schema}"), [], dialect: :postgres)

      {:ok, _} = Connection.query(single, "CREATE TABLE marks (n BIGINT)", [], dialect: :postgres)

      write = fn txn -> Connection.txn_query(txn, "INSERT INTO marks (n) VALUES (1)") end

      assert_raise RuntimeError, fn ->
        Connection.transaction(
          single,
          fn txn ->
            {:ok, _} = write.(txn)
            raise "boom"
          end,
          5_000
        )
      end

      assert {:error, :nope} =
               Connection.transaction(
                 single,
                 fn txn ->
                   {:ok, _} = write.(txn)
                   {:error, :nope}
                 end,
                 5_000
               )

      # One connection, so a transaction left open would still hold the
      # transaction id its insert was given.
      assert {:ok, %{rows: [[1]]}} =
               Connection.query(
                 single,
                 "SELECT pg_current_xact_id_if_assigned() IS NULL",
                 [],
                 dialect: :postgres
               )

      assert {:ok, %{rows: [[0]]}} = Connection.query(single, "SELECT COUNT(*) FROM marks")
    end

    test "a recoverable statement's failure leaves the transaction open, as on SQLite",
         %{pool: pool} do
      query!(pool, "INSERT INTO items (name) VALUES (?1)", ["taken"])
      insert = "INSERT INTO items (name) VALUES (?1)"

      assert {:ok, :done} =
               Connection.transaction(
                 pool,
                 fn txn ->
                   assert {:error, "UNIQUE constraint failed: items.name"} =
                            Connection.txn_query(txn, insert, ["taken"], recoverable: true)

                   {:ok, _} = Connection.txn_query(txn, insert, ["after"])
                   {:ok, :done}
                 end,
                 5_000
               )

      assert [["after"], ["taken"]] = query!(pool, "SELECT name FROM items ORDER BY name")
    end

    test "any other failed statement ends the transaction, and a commit after it rolls back",
         %{pool: pool} do
      query!(pool, "INSERT INTO items (name) VALUES (?1)", ["taken"])
      insert = "INSERT INTO items (name) VALUES (?1)"

      assert {:error, {:commit_failed, :rollback}} =
               Connection.transaction(
                 pool,
                 fn txn ->
                   {:ok, _} = Connection.txn_query(txn, insert, ["before"])
                   {:error, _} = Connection.txn_query(txn, insert, ["taken"])
                   assert {:error, message} = Connection.txn_query(txn, insert, ["after"])
                   assert message =~ "current transaction is aborted"
                   {:ok, :ignored_the_error}
                 end,
                 5_000
               )

      assert [["taken"]] = query!(pool, "SELECT name FROM items ORDER BY name")
    end

    test "writes outside a savepoint use no subtransaction", %{pool: pool} do
      subxacts = """
      SELECT s.subxact_count
      FROM pg_stat_get_backend_idset() AS b(id)
      CROSS JOIN LATERAL pg_stat_get_backend_subxact(b.id) AS s
      WHERE pg_stat_get_backend_pid(b.id) = pg_backend_pid()
      """

      count = fn opts ->
        Connection.transaction(
          pool,
          fn txn ->
            for n <- 1..100 do
              {:ok, _} =
                Connection.txn_query(txn, "INSERT INTO items (name) VALUES (?1)", ["w#{n}"], opts)
            end

            with {:ok, %{rows: [[count]]}} <-
                   Connection.txn_query(txn, subxacts, [], dialect: :postgres),
                 do: {:error, count}
          end,
          30_000
        )
      end

      # More than 64 subtransactions overflow PostgreSQL's per-backend cache,
      # which slows every snapshot on the server.
      assert {:error, 0} = count.([])
      assert {:error, savepoints} = count.(recoverable: true)
      assert savepoints >= 64
    end

    test "concurrent read-check-write transactions lose no update", %{pool: pool} do
      query!(pool, "INSERT INTO items (name, n) VALUES ('counter', 0)")

      test_pid = self()
      handler = {__MODULE__, :retries, make_ref()}

      :telemetry.attach(
        handler,
        [:optimal_engine, :store, :retry],
        fn _event, _measurements, metadata, _config -> send(test_pid, {:retried, metadata}) end,
        nil
      )

      on_exit(fn -> :telemetry.detach(handler) end)

      increment = fn ->
        Connection.transaction(
          pool,
          fn txn ->
            {:ok, %{rows: [[n]]}} =
              Connection.txn_query(txn, "SELECT n FROM items WHERE name = 'counter'")

            Process.sleep(2)

            {:ok, %{num_rows: 1}} =
              Connection.txn_query(txn, "UPDATE items SET n = ?1 WHERE name = 'counter'", [n + 1])

            {:ok, n + 1}
          end,
          30_000
        )
      end

      # A COMMIT that fails with a serialization failure is retried on the
      # same connection; it never closes the connection.
      {results, log} =
        with_log(fn ->
          1..24
          |> Task.async_stream(fn _ -> increment.() end, max_concurrency: 6, timeout: 60_000)
          |> Enum.map(fn {:ok, result} -> result end)
        end)

      refute log =~ "disconnected"

      assert Enum.all?(results, &match?({:ok, _}, &1)), inspect(results)
      assert [[24]] = query!(pool, "SELECT n FROM items WHERE name = 'counter'")

      assert results |> Enum.map(fn {:ok, n} -> n end) |> Enum.sort() == Enum.to_list(1..24)

      # Six writers on one row conflict; PostgreSQL aborted some and they ran again.
      assert_received {:retried, %{scope: :transaction, reason: :serialization_failure}}
    end
  end

  describe "retries" do
    setup %{pool: pool} do
      test_pid = self()
      handler = {__MODULE__, :retry_events, make_ref()}

      :telemetry.attach(
        handler,
        [:optimal_engine, :store, :retry],
        fn _event, measurements, metadata, _config ->
          send(test_pid, {:retried, measurements.attempt, metadata})
        end,
        nil
      )

      on_exit(fn -> :telemetry.detach(handler) end)

      # A function that fails with the SQLSTATE in its argument while the
      # sequence is below the given call count, then returns 1.
      {:ok, _} =
        Connection.query(
          pool,
          "CREATE SEQUENCE IF NOT EXISTS conflict_calls",
          [],
          dialect: :postgres
        )

      {:ok, _} =
        Connection.query(
          pool,
          """
          CREATE OR REPLACE FUNCTION conflict_until(code text, calls bigint) RETURNS bigint
          LANGUAGE plpgsql AS $$
          BEGIN
            IF nextval('conflict_calls') <= calls THEN
              RAISE EXCEPTION 'conflict' USING ERRCODE = code;
            END IF;
            RETURN 1;
          END $$
          """,
          [],
          dialect: :postgres
        )

      {:ok, _} =
        Connection.query(pool, "ALTER SEQUENCE conflict_calls RESTART", [], dialect: :postgres)

      :ok
    end

    test "a statement that meets a serialization failure runs again", %{pool: pool} do
      assert {:ok, %{rows: [[1]]}} =
               Connection.query(pool, "SELECT conflict_until('40001', 2)")

      assert_received {:retried, 1, %{scope: :statement, reason: :serialization_failure}}
      assert_received {:retried, 2, %{scope: :statement, reason: :serialization_failure}}
    end

    test "a detected deadlock is retried like a serialization failure", %{pool: pool} do
      assert {:ok, %{rows: [[1]]}} = Connection.query(pool, "SELECT conflict_until('40P01', 1)")
      assert_received {:retried, 1, %{scope: :statement, reason: :deadlock_detected}}
    end

    test "a statement stops after its attempts and says so", %{pool: pool} do
      assert {:error, {:serialization_failure, detail}} =
               Connection.query(pool, "SELECT conflict_until('40001', 1000)", [], timeout: 60_000)

      assert detail =~ "gave up after 25 attempts"
    end

    test "a transaction stops at its deadline", %{pool: pool} do
      started = System.monotonic_time(:millisecond)

      assert {:error, {:serialization_failure, detail}} =
               Connection.transaction(
                 pool,
                 &Connection.txn_query(&1, "SELECT conflict_until('40001', 1000)"),
                 300
               )

      assert detail =~ "gave up after"
      refute detail =~ "after 25 attempts"
      assert System.monotonic_time(:millisecond) - started < 2_000
    end

    test "a fun that swallows a serialization failure still runs again", %{pool: pool} do
      runs = :counters.new(1, [])

      assert {:ok, :done} =
               Connection.transaction(
                 pool,
                 fn txn ->
                   :counters.add(runs, 1, 1)
                   _ignored = Connection.txn_query(txn, "SELECT conflict_until('40001', 1)")
                   {:ok, :done}
                 end,
                 5_000
               )

      assert :counters.get(runs, 1) == 2
      assert_received {:retried, 1, %{scope: :transaction, reason: :serialization_failure}}
    end
  end

  describe "parity with SQLite" do
    setup do
      {:ok, db} = Exqlite.Sqlite3.open(":memory:")
      :ok = Exqlite.Sqlite3.execute(db, @sqlite_items)
      on_exit(fn -> Exqlite.Sqlite3.close(db) end)
      %{db: db}
    end

    defp sqlite!(db, sql, params) do
      {:ok, statement} = Exqlite.Sqlite3.prepare(db, sql)
      :ok = Exqlite.Sqlite3.bind(statement, params)
      {:ok, rows} = Exqlite.Sqlite3.fetch_all(db, statement)
      Exqlite.Sqlite3.release(db, statement)
      rows
    end

    test "the same statements return the same rows", %{pool: pool, db: db} do
      writes = [
        {"INSERT INTO items (name, n, score, meta) VALUES (?1, ?2, ?3, ?4)",
         ["beta", 2, 0.5, ~s({"kind": "x", "tags": {"a": "1"}})]},
        {"INSERT INTO items (name, n, score, meta) VALUES (?, ?, ?, ?)",
         ["Alpha", nil, 1.25, ~s({"kind": "y"})]},
        {"INSERT INTO items (name, n, score, meta) VALUES (?1, ?2, ?3, ?4)",
         ["alpha", 10, nil, nil]},
        {"INSERT INTO items (name, n) VALUES (?1, ?2)", ["École", 3]},
        {"INSERT INTO items (name, n) VALUES (?1, ?2)", ["école", 4]},
        {"INSERT INTO items (name, n, meta) VALUES (?1, ?2, ?3)",
         ["a\\b", 6, ~s({"kind": "x", "num": 1, "flag": true, "none": null})]},
        {"INSERT INTO items (name, n, score, meta) VALUES (?1, ?2, ?3, ?4)",
         ["50%", 7, 2.5, ~s({"num": 2, "flag": false})]},
        {"INSERT INTO items (name, n, meta) VALUES (?1, ?2, ?3)", ["50\\%", 8, ~s({"num": "1"})]},
        {"INSERT INTO items (name) VALUES (?1)", ["trail\\"]},
        {"INSERT OR IGNORE INTO items (name, n) VALUES (?1, ?2)", ["beta", 99]},
        {"UPDATE items SET n = n + ?1 WHERE name = ?2", [5, "alpha"]}
      ]

      for {sql, params} <- writes do
        sqlite!(db, sql, params)
        {:ok, _} = Connection.query(pool, sql, params)
      end

      reads = [
        {"SELECT name, n, score FROM items ORDER BY name", []},
        {"SELECT name FROM items WHERE n IS NULL", []},
        {"SELECT name FROM items WHERE n > ?1 ORDER BY n DESC", [1]},
        {"SELECT COUNT(*), SUM(n), MIN(score), MAX(score) FROM items", []},
        {"SELECT name, json_extract(meta, '$.kind') FROM items ORDER BY name", []},
        {"SELECT name FROM items WHERE json_extract(meta, '$.tags.a') = ?1", ["1"]},
        {"SELECT COALESCE(n, -1) FROM items ORDER BY name", []},
        # The part of a value before a separator, empty when it is absent.
        {"SELECT name, substr(name, 1, instr(name, 'a') - 1) FROM items ORDER BY name", []},
        {"SELECT substr(?1, 1, instr(?1, ':') - 1)", ["acme:ops"]},
        {"SELECT substr(?1, 1, instr(?1, ':') - 1)", ["default"]},
        {"SELECT substr(?1, 1, instr(?1, ':') - 1)", [":ops"]},
        {"SELECT substr(?1, 1, instr(?1, ':') - 1)", ["a:b:c"]},
        # NULL in gives NULL out, on both; the empty string gives ''.
        {"SELECT substr(?1, 1, instr(?1, ':') - 1)", [nil]},
        {"SELECT substr(?1, 1, instr(?1, ?2) - 1)", ["a:b", nil]},
        {"SELECT substr(?1, 1, instr(?1, ':') - 1)", [""]},
        # Characters, not bytes, in a UTF8 database as in SQLite.
        {"SELECT substr(?1, 1, instr(?1, ':') - 1)", ["école:ops"]},
        {"SELECT substr(?1, 1, instr(?1, '・') - 1)", ["日本・東京"]},
        {"SELECT name FROM items WHERE name IN (?1, ?2) ORDER BY name", ["alpha", "beta"]},
        {"SELECT name FROM items ORDER BY name LIMIT ?1 OFFSET ?2", [2, 1]},
        {"SELECT n IS NULL, n > 3 FROM items ORDER BY name", []},
        {"SELECT name FROM items WHERE name LIKE ?1 ORDER BY name", ["al%"]},
        {"SELECT name FROM items WHERE name NOT LIKE ?1 ORDER BY name", ["%A%"]},
        {"SELECT name FROM items WHERE name LIKE ?1 ORDER BY name", ["é%"]},
        # A backslash is an ordinary character unless ESCAPE names it.
        {"SELECT name FROM items WHERE name LIKE ?1 ORDER BY name", ["a\\b"]},
        {"SELECT name FROM items WHERE name LIKE ?1 ORDER BY name", ["50\\%"]},
        {"SELECT name FROM items WHERE name LIKE ?1 ORDER BY name", ["%\\"]},
        {"SELECT name FROM items WHERE name LIKE ?1 ESCAPE '\\' ORDER BY name", ["50\\%"]},
        {"SELECT name FROM items WHERE name LIKE '%' || ?1 || '%' ORDER BY name", ["%"]},
        # NULL sorts first ascending and last descending, as on SQLite.
        {"SELECT name FROM items ORDER BY n, name", []},
        {"SELECT name FROM items ORDER BY n DESC, name", []},
        {"SELECT name FROM items ORDER BY score DESC, n", []},
        {"SELECT name FROM items ORDER BY n NULLS LAST, name", []},
        {"SELECT name FROM items WHERE n IS ?1 ORDER BY name", [nil]},
        {"SELECT name FROM items WHERE n IS NOT ?1 ORDER BY name", [3]},
        {"SELECT name FROM items WHERE name IS NOT 'beta' ORDER BY name", []},
        # SQLite ignores a numbered parameter the statement never names.
        {"SELECT name FROM items WHERE name = ?2 OR name = ?3 ORDER BY name",
         ["unused", "beta", "Alpha"]},
        # json_extract in every form the dialect translates.
        {"SELECT name FROM items WHERE json_extract(meta, '$.kind') IS NULL ORDER BY name", []},
